/*
**	A whole file into a new buffer (0x6839E0; inlined into the start-up).
*/
void * Load_Alloc_Data(char const * filename)
{
	file_auto_ptr file(_TheFileFactory, filename);
	file->Open();
	int size = file->Size();
	G_ASSERT(size);
	void * buffer = new char[size];
	file->Read(buffer, size);
	file->Close();
	return(buffer);
}









/*
**	A three-byte remap from a Remaps row (0x683AC0, no caller): bytes 0 and 1 of the row, then the entry val_norm
**	of the way along the rest of it. Only type 16 has one.
*/
unsigned char * Unknown_683AC0(float val_norm, int type, unsigned char * remap)
{
	G_ASSERT(val_norm >= 0.0f);
	G_ASSERT(val_norm <= 1.0f);
	G_ASSERT(remap);

	switch (type) {
		case 16:
		{
			remap[0] = Remaps[type][0];
			remap[1] = Remaps[type][1];
			int count = RemapSizes[type] - 2;
			int index = (int)(count * val_norm);
			if (index == count) {
				index--;
			}
			remap[2] = Remaps[type][index + 2];
			return(remap);
		}


		default:
			G_ASSERT(false);
			break;
	}
	return(remap);
}


