/*
**	Start-up (0x6832C0, called by 0x526DE0): the font files into FontData, fontpal.pcx's palette into Palette and
**	its rows into Remaps, the converter from Palette to Unknown_B8F870.
*/
void Unknown_6832C0(void)
{
	Unknown_684E00();

	FontData[0] = DefaultFontData;
	for (int style = 1; style < STYLE_COUNT; style++) {
		G_ASSERT(!FontData[style]);
		FontData[style] = Load_Alloc_Data(FontNames[style]);
	}

	file_auto_ptr file(_TheFileFactory, "fontpal.pcx");
	Surface * surface = Read_PCX_File(*file, &Palette);
	unsigned char * pal = Palette;
	for (int index = 0; index < 768; index++) {
		*pal++ >>= 2;
	}




	unsigned char * rowptr = (unsigned char *)surface->Lock();
	G_ASSERT(rowptr);

	RemapSizes[0] = 256;
	Remaps[0] = new unsigned char[256];
	for (int row = 1; row < REMAP_COUNT; row++) {
		unsigned char buffer[256];
		int count;
		for (count = 0; count < 256; count++) {
			buffer[count] = rowptr[count];
			if (buffer[count] == 0xFF) break;
		}
		RemapSizes[row] = count + 1;
		Remaps[row] = new unsigned char[count + 1];
		memcpy(Remaps[row] + 1, buffer, count);
		Remaps[row][0] = 0;
		rowptr += surface->Get_Width();
	}
	surface->Unlock();
	delete surface;

	Converter = new ConvertClass(Palette, (PaletteClass const &)Unknown_B8F870, BSurface(16, 16, 1));
	DefaultFont.Set_XSpacing(-1);
}


