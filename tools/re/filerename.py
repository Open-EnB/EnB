"""Rename app source files (a .cpp and its .h) and everything that names them.

    python tools/re/filerename.py packets/pkunknown_ADDR=packets/gameedit/pkgexyz client/unknown_abc=client/abc_def [--write]
    python tools/re/filerename.py --from-file LIST.tsv [--write]      (old<TAB>new per line, app-relative stems)

Dry run unless --write. Per pair (stems relative to app/, forward slashes, no extension):
  1. `git mv` of the .cpp and the .h, and of their ledger shards (docs/data/imports/app/<base>.json and
     headers/<dir>/<base>.h.json; a shard is named by the file's base name).
  2. Quoted #include paths: an include that resolves, relative to its includer, to a moved header (or any include
     inside a file that changed folder) is rewritten relative to the new places, with backslashes as the tree's.
  3. The include guard `OLD_H` -> `NEW_H` (with whatever underscores lead it), in every file: another header may
     test it (`#ifdef UNKNOWN_675120_H` in ui_combobox.h cost a failed verify on 2026-11-27).
  4. The app-relative path (`packets/old`, `packets\\old`, `packets\\\\old`) and then the bare base name, as whole
     words, in TEXT_DIRS (source, tools, the ledger shards, accepted-corrections.json). Other docs are not
     touched: the generated ones are regenerated by their tools, the log entries are history.
  5. The stale build/app/obj/<old base>.obj is deleted (it can still link in: workflow.md 3.6).
It stops before changing anything when a new base name is already a source file of the app (objects and shards are
named by base name) or a pair's old file is missing. It prints the includes of a moved header it could not resolve
(reached through an include directory): fix those by hand.

Afterwards: verify (the pairs move with the file: D66 kind iv, pairs_cmp's `moves`), the file-name tag on the
include guard, the shard's description (ledger.py describe), tools that name packet files by address
(pkemit.py's NAMED / HAND), and `python tools/re/names.py`.
"""
import argparse
import io
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
APP = os.path.join(ROOT, 'app')
SRC_EXT = ('.cpp', '.h', '.inl', '.c', '.rc')
TEXT_DIRS = ['app', 'tests', 'stubs', 'programs', 'libs', 'tools', 'docs/data/imports']
TEXT_FILES = ['docs/data/accepted-corrections.json']
TEXT_EXT = SRC_EXT + ('.py', '.json', '.tsv', '.txt', '.md', '.scn', '.dsp', '.dsw', '.mak', '.lst')
SKIP_DIRS = {'obj', '.git', '__pycache__', 'proposals', 'exact'}
INCLUDE = re.compile(r'^([ \t]*#[ \t]*include[ \t]*")([^"\n]+)(")', re.M)


def git(*args):
    subprocess.run(['git'] + list(args), cwd=ROOT, check=True)


def text_files():
    for d in TEXT_DIRS:
        for dp, dn, fn in os.walk(os.path.join(ROOT, d)):
            dn[:] = [x for x in dn if x not in SKIP_DIRS]
            for f in fn:
                if f.lower().endswith(TEXT_EXT):
                    yield os.path.join(dp, f)
    for f in TEXT_FILES:
        yield os.path.join(ROOT, f)


def word(s):
    return re.compile(r'(?<![A-Za-z0-9_])' + re.escape(s) + r'(?![A-Za-z0-9_])')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('pairs', nargs='*')
    ap.add_argument('--from-file')
    ap.add_argument('--write', action='store_true')
    a = ap.parse_args()
    pairs = [p.split('=') for p in a.pairs]
    if a.from_file:
        for ln in io.open(a.from_file, encoding='utf-8'):
            ln = ln.strip()
            if ln and not ln.startswith('#'):
                pairs.append(ln.split('\t')[:2])
    if not pairs:
        ap.error('no pairs')

    # checks
    bases = {}
    for dp, dn, fn in os.walk(APP):
        dn[:] = [x for x in dn if x not in SKIP_DIRS]
        for f in fn:
            if f.lower().endswith(('.cpp', '.c')):
                bases[os.path.splitext(f)[0].lower()] = os.path.join(dp, f)
    moved = {}                       # absolute old path -> absolute new path (sources)
    shards = []                      # (old rel, new rel) under docs/data/imports/app
    errors = []
    for old, new in pairs:
        ob, nb = os.path.basename(old), os.path.basename(new)
        found = False
        for ext in ('.cpp', '.h'):
            src = os.path.join(APP, old + ext)
            if os.path.exists(src):
                found = True
                moved[os.path.normcase(os.path.normpath(src))] = os.path.normpath(os.path.join(APP, new + ext))
                if os.path.exists(os.path.join(APP, new + ext)):
                    errors.append('%s%s exists' % (new, ext))
        if not found:
            errors.append('%s: no .cpp or .h' % old)
        if nb.lower() in bases and nb.lower() != ob.lower():
            errors.append('%s: base name already used by %s' % (new, os.path.relpath(bases[nb.lower()], ROOT)))
        shards.append((ob + '.json', nb + '.json'))
        shards.append(('headers/%s.h.json' % old, 'headers/%s.h.json' % new))
    if len({os.path.basename(n).lower() for _, n in pairs}) != len(pairs):
        errors.append('two pairs share a new base name')
    if errors:
        sys.exit('filerename: ' + '; '.join(errors))

    # 2. includes, computed on the tree as it is now
    unresolved, inc_edits = [], {}
    old_bases = {os.path.basename(o).lower() + '.h': n for o, n in pairs}
    sources = [p for p in text_files() if p.lower().endswith(SRC_EXT)]
    for p in sources:
        key = os.path.normcase(os.path.normpath(p))
        new_self = moved.get(key, p)
        old_dir, new_dir = os.path.dirname(p), os.path.dirname(new_self)
        text = io.open(p, encoding='latin-1', newline='').read()

        def sub(m):
            inc = m.group(2)
            target = os.path.normpath(os.path.join(old_dir, inc.replace('\\', os.sep)))
            tkey = os.path.normcase(target)
            if tkey in moved:
                dest = moved[tkey]
            elif os.path.exists(target):
                if old_dir == new_dir:
                    return m.group(0)
                dest = target
            else:
                if os.path.basename(inc.replace('\\', '/')).lower() in old_bases:
                    unresolved.append('%s: %s' % (os.path.relpath(p, ROOT), inc))
                return m.group(0)
            rel = os.path.relpath(dest, new_dir).replace(os.sep, '\\')
            return m.group(1) + rel + m.group(3)
        out = INCLUDE.sub(sub, text)
        if out != text:
            inc_edits[p] = out

    # 3 + 4. guards, paths, base names
    reps = []
    for old, new in pairs:
        ob, nb = os.path.basename(old), os.path.basename(new)
        reps.append((re.compile(r'(?<![A-Za-z0-9_])(_*)' + re.escape(ob.upper()) + r'_H(?![A-Za-z0-9_])'), '\\g<1>' + nb.upper() + '_H'))
        for sep in ('/', '\\', '\\\\'):
            reps.append((word(old.replace('/', sep)), new.replace('/', sep)))
    for old, new in pairs:            # the bare names last, so a path is replaced as a whole first
        reps.append((word(os.path.basename(old)), os.path.basename(new)))
    text_edits, hits = {}, 0
    for p in text_files():
        try:
            text = inc_edits.get(p) or io.open(p, encoding='latin-1', newline='').read()
        except OSError:
            continue
        out = text
        for pat, new in reps:
            out, k = pat.subn(lambda m, new=new: m.expand(new) if new.startswith('\\g<1>') else new, out)
            hits += k
        if out != text or p in inc_edits:
            text_edits[p] = out

    print('%s: %d pairs, %d source files to move, %d files edited (%d include files, %d name replacements)' % (
        'written' if a.write else 'dry run', len(pairs), len(moved), len(text_edits), len(inc_edits), hits))
    for u in unresolved:
        print('  include not resolved relative to its includer, fix by hand: ' + u)
    if not a.write:
        return
    for p, out in text_edits.items():
        with io.open(p, 'w', encoding='latin-1', newline='') as f:
            f.write(out)
    for src, dst in moved.items():
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        git('mv', os.path.relpath(src, ROOT), os.path.relpath(dst, ROOT))
    base = os.path.join(ROOT, 'docs', 'data', 'imports', 'app')
    for o, n in shards:
        if os.path.exists(os.path.join(base, o)):
            os.makedirs(os.path.dirname(os.path.join(base, n)), exist_ok=True)
            git('mv', os.path.relpath(os.path.join(base, o), ROOT), os.path.relpath(os.path.join(base, n), ROOT))
    for old, _ in pairs:
        obj = os.path.join(ROOT, 'build', 'app', 'obj', os.path.basename(old) + '.obj')
        if os.path.exists(obj):
            os.remove(obj)
            print('  deleted the stale ' + os.path.relpath(obj, ROOT))


if __name__ == '__main__':
    main()
