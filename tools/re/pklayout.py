"""LY-01 (test plan): the packet classes' layout checked at compile time by VC6: every class the packet factory
0x869790 makes has the size the client's case `new`s (docs/data/packet-factory.txt), and every data member a
rebuilt header gives an offset comment (`// +0xNN`) sits at that offset.

    python tools/re/pklayout.py gen [--check]      writes tests/pklayout/pk_layout.cpp (GENERATED)
    python tools/re/pklayout.py build [--pool 1]   compiles and links tests/pklayout on a VC6 VM (a failed check is
                                                   a compile error naming the class and member)

The offsets' evidence: where tools/re/pkdecode.py decoded the class from the client (its constructor's
RawPacketClass::Get calls on members, .work/pkdecode/decoded.pkl) the member at that offset is the client's
('client' in the line's comment); else the header's own comment ('header': drafted from the client by pkemit.py or
by hand). A check is `typedef char NAME[(cond) ? 1 : -1];` (VC6 has no static_assert); offsets by offsetof. A
member of a #pragma pack class is checked the same way (offsetof follows the packing).
"""
import argparse
import os
import pickle
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)
import pkclasses  # noqa: E402

FACTORY = os.path.join(ROOT, 'docs', 'data', 'packet-factory.txt')
DECODED = os.path.join(ROOT, '.work', 'pkdecode', 'decoded.pkl')


def _main_tree():
    """The main checkout of a builder worktree (.work/wt/NAME): its .work holds pkdecode's output."""
    parts = os.path.normpath(ROOT).split(os.sep)
    if len(parts) > 3 and parts[-3:-1] == ['.work', 'wt']:
        return os.sep.join(parts[:-3])
    return ROOT


if not os.path.isfile(DECODED):
    DECODED = os.path.join(_main_tree(), '.work', 'pkdecode', 'decoded.pkl')
OUT_DIR = os.path.join(ROOT, 'tests', 'pklayout')
OUT = os.path.join(OUT_DIR, 'pk_layout.cpp')
PKDIR = os.path.join(ROOT, 'app', 'packets')

_MEMBER = re.compile(r'^\s+(?!virtual\b|static\b|typedef\b|friend\b|enum\b|using\b)([A-Za-z_][\w:<>, \*&]*?[\s\*&])'
                     r'(\w+)\s*(\[[^\]]*\])*\s*;\s*//\s*\+0x([0-9A-Fa-f]+)\b')


def factory_sizes(path=FACTORY):
    """{opcode: bytes} from packet-factory.txt."""
    out = {}
    for line in open(path, encoding='utf-8'):
        m = re.match(r'^\s*(\d+)\s+0x[0-9A-Fa-f]+\s+\S+\s+0x([0-9A-Fa-f]+)\s', line)
        if m:
            out[int(m.group(1))] = int(m.group(2), 16)
    return out


def header_classes(text):
    """{class: [(member, offset)]} of a header's classes (members with an offset comment, in order)."""
    out, cur, depth = {}, None, 0
    for line in text.splitlines():
        if cur is None:
            m = re.match(r'^(?:class|struct)\s+(\w+)\b[^;]*$', line)
            if m:
                cur, depth = m.group(1), 0
                out[cur] = []
            continue
        depth += line.count('{') - line.count('}')
        if depth <= 0 and '}' in line:
            cur = None
            continue
        if depth == 1 and '(' not in line.split('//')[0]:
            m = _MEMBER.match(line)
            if m:
                out[cur].append((m.group(2), int(m.group(4), 16)))
    return out


def decoded_offsets(path=DECODED):
    """{opcode: {offset}} the client's constructors read members at (pkdecode.py); {} without the file."""
    if not os.path.isfile(path):
        return {}
    out = {}
    for f in pickle.load(open(path, 'rb')):
        for c in f.get('classes', []):
            out.setdefault(c['op'], set()).update(m['off'] for m in c.get('members', []))
    return out


def generate():
    sizes = factory_sizes()
    rebuilt = pkclasses.rebuilt_classes()
    dec = decoded_offsets()
    lines = ['// Earth & Beyond client (reconstruction)',
             '// GENERATED by tools/re/pklayout.py (test plan LY-01): do not edit by hand.',
             '// Each line fails to compile (a negative array size) when a packet class\'s size is not the client\'s',
             '// (the packet factory 0x869790\'s new, docs/data/packet-factory.txt) or a member is not at its offset.',
             '#include <stddef.h>', '#include "pk_classes.h"', '',
             '#define LY_SIZE(c, n) typedef char LY_size_##c[(sizeof(c) == (n)) ? 1 : -1];',
             '#define LY_OFF(c, m, n) typedef char LY_off_##c##_##m[(offsetof(c, m) == (n)) ? 1 : -1];', '']
    n_size = n_off = n_client = 0
    seen = set()
    headers = {}
    for op in sorted(sizes):
        if op not in rebuilt:
            lines.append(f'// opcode {op}: no rebuilt class')
            continue
        name, inc = rebuilt[op]
        if name in seen:
            continue
        seen.add(name)
        lines.append(f'LY_SIZE({name}, 0x{sizes[op]:X})\t// opcode {op} ({inc})')
        n_size += 1
        if inc not in headers:
            headers[inc] = header_classes(open(os.path.join(PKDIR, inc), encoding='latin1').read())
        for member, off in headers[inc].get(name, []):
            src = 'client' if off in dec.get(op, ()) else 'header'
            n_client += src == 'client'
            lines.append(f'LY_OFF({name}, {member}, 0x{off:X})\t// {src}')
            n_off += 1
    lines += ['', f'int Packet_Layout_Checks() {{ return {n_size + n_off}; }}\t// {n_size} sizes, {n_off} offsets '
              f'({n_client} the client\'s by pkdecode, {n_off - n_client} the headers\')', '']
    return '\r\n'.join(lines), n_size, n_off, n_client


MAIN = '''// Earth & Beyond client (reconstruction)
// tests/pklayout (test plan LY-01): the checks are compile-time (pk_layout.cpp, tools/re/pklayout.py); the program
// only reports how many there are.
#include <stdio.h>
int Packet_Layout_Checks();
int main()
{
	printf("pklayout: %d layout checks compiled\\n", Packet_Layout_Checks());
	return 0;
}
'''


def build(pool):
    sys.path.insert(0, os.path.join(ROOT, 'tools', 'vc6'))
    import build as B
    B.PROGRAMS['pklayout'] = {'dir': os.path.relpath(OUT_DIR, ROOT), 'flags': B.I.LIB_FLAGS['app'],
                              'defines': B.I.APP_LIBS['app']['defines'], 'subsystem': 'console', 'runtime': [],
                              'libs': [], 'stubs': False, 'strict': True}
    out = os.path.join(ROOT, 'build')
    if pool:
        with B.I.pool_lease(pool, None):
            B.link_program('pklayout', out)
    else:
        B.link_program('pklayout', out)
    print('pklayout: built', os.path.join(out, 'programs', 'pklayout', 'pklayout.exe'))


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    sub = ap.add_subparsers(dest='cmd', required=True)
    g = sub.add_parser('gen')
    g.add_argument('--check', action='store_true')
    b = sub.add_parser('build')
    b.add_argument('--pool', type=int, default=1)
    a = ap.parse_args(argv)
    if a.cmd == 'build':
        build(a.pool)
        return 0
    text, ns, no, nc = generate()
    old = open(OUT, encoding='latin1', newline='').read() if os.path.isfile(OUT) else None
    if a.check:
        print('pklayout: up to date' if old == text else 'pklayout: pk_layout.cpp would change')
        return 0 if old == text else 1
    os.makedirs(OUT_DIR, exist_ok=True)
    open(OUT, 'w', encoding='latin1', newline='').write(text)
    main_cpp = os.path.join(OUT_DIR, 'main.cpp')
    if not os.path.isfile(main_cpp):
        open(main_cpp, 'w', encoding='latin1', newline='').write(MAIN.replace('\n', '\r\n'))
    print(f'pklayout: {OUT}: {ns} sizes, {no} offsets ({nc} the client\'s by pkdecode)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
