"""TN1: carry the class renames of docs/data/class-renames.tsv into the source (progress.md section 4).

    python tools/re/thunknames/classrename.py                      dry run of every `keep` row that is safe to script
    python tools/re/thunknames/classrename.py --write              ... and write it
    python tools/re/thunknames/classrename.py --only A,B --write   only these classes (our names)
    python tools/re/thunknames/classrename.py --collisions         also rows whose retail name is already an identifier
    python tools/re/thunknames/classrename.py --selftest

What it renames, as whole identifiers only:
  - the source trees (SRC_DIRS): code and comments. String and character literals are left alone (they are the
    client's own bytes: assert texts, ini keys, file names in #include), and so is a double-quoted span inside a
    comment (a quoted client string). No line is added or removed (__LINE__ in asserts).
  - the class's definition gets the D56 tag `// NAME 5: thunk order A, binary.md 5.11`, A / B / C being the row's
    confidence (an older NAME tag on that line is replaced; one on the comment line above is kept behind the
    new tag).
  - docs/data/symbols.json and tools/re/symbols_named.json: the decorated names, through mangle.rename_all.
  - TOOL_FILES: hand-written tool inputs and tests that spell the class as an identifier or inside a decorated name.
Generated docs (imports.md, names-review.md, ...) are regenerated by their tools, never edited here.

Rows it leaves out unless named with --only: split suspects, rows whose class the source does not spell, and
(without --collisions) rows whose retail name the source's code already uses (a mention in a comment is none). It stops if a row's
retail name is another row's old name (a chain) or two rows share a retail name (a merge).

A report goes to .work/names/classrename-report.tsv: per class the occurrences and files, the definition tagged
or not, and every use inside a stringizing macro's arguments (the string the compiler makes would change).
"""
import argparse
import collections
import csv
import io
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mangle  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', '..'))
SRC_DIRS = ['app', 'libs', 'ww3d2', 'wwaudio', 'wwdebug', 'wwlib', 'wwmath', 'wwsaveload', 'wwshade', 'binkmovie',
            'programs', 'tests', 'stubs']
SRC_EXT = {'.cpp', '.h', '.inl', '.c', '.hpp'}
SYMBOL_FILES = ['docs/data/symbols.json', 'tools/re/symbols_named.json']
TOOL_FILES = ['tools/re/auxroots.py', 'tools/re/objmatch.py', 'tools/re/test_objmatch.py', 'tools/re/auxextract.py',
              'tools/re/pkclasses.py', 'tools/re/pkdecode.py', 'tools/re/pkemit.py', 'tools/re/pklayout.py',
              'tools/re/crtseq.py', 'tools/re/symbols.py', 'tools/re/behaudit_known.tsv', 'tools/re/test_behaudit.py',
              'tools/re/test_trybatch.py', 'tools/test_linkgate.py', 'tools/test_standins.py',
              'tools/harness/clienttest.py', 'tools/harness/msglisten.py', 'tools/harness/udpreplay.py']
TAG = '// NAME 5: thunk order %s, binary.md 5.11'      # % the row's confidence (A, B or C)
IDENT = re.compile(r'[A-Za-z_][A-Za-z0-9_]*')
NAME_TAG = re.compile(r'//\s*NAME\s+\d\s*:')


def load_rows(verdicts=('keep',)):
    p = os.path.join(ROOT, 'docs', 'data', 'class-renames.tsv')
    with io.open(p, encoding='utf-8') as f:
        return [r for r in csv.DictReader(f, delimiter='\t') if r['verdict'] in verdicts]


def source_files():
    for d in SRC_DIRS:
        for dp, dn, fn in os.walk(os.path.join(ROOT, d)):
            dn[:] = [x for x in dn if x not in ('obj', '.git')]
            for f in sorted(fn):
                if os.path.splitext(f)[1].lower() in SRC_EXT:
                    yield os.path.join(dp, f)


def segments(text):
    """Split C / C++ text into (kind, chunk): 'code', 'comment' (renamed) and 'lit' (string / char literal, and the
    rest of an #include line: left alone). A double-quoted span inside a comment is 'lit' too."""
    out = []
    i, n, start = 0, len(text), 0

    def flush(kind, a, b):
        if b > a:
            out.append((kind, text[a:b]))

    while i < n:
        c = text[i]
        if c == '/' and i + 1 < n and text[i + 1] in '/*':
            flush('code', start, i)
            if text[i + 1] == '/':
                j = text.find('\n', i)
                j = n if j < 0 else j
            else:
                j = text.find('*/', i + 2)
                j = n if j < 0 else j + 2
            body = text[i:j]
            k = 0
            for m in re.finditer(r'"[^"\n]*"', body):
                flush_c = body[k:m.start()]
                if flush_c:
                    out.append(('comment', flush_c))
                out.append(('lit', m.group(0)))
                k = m.end()
            if body[k:]:
                out.append(('comment', body[k:]))
            i = start = j
        elif c == '"' or c == "'":
            # a digit separator or apostrophe cannot occur in VC6 code outside a literal
            flush('code', start, i)
            j = i + 1
            while j < n and text[j] != c and text[j] != '\n':
                j += 2 if text[j] == '\\' else 1
            j = min(j + 1, n)
            out.append(('lit', text[i:j]))
            i = start = j
        elif c == '#':
            m = re.compile(r'#[ \t]*include\b[^\n]*').match(text, i)
            if m and text[:i].rsplit('\n', 1)[-1].strip() == '':
                flush('code', start, i)
                out.append(('lit', m.group(0)))
                i = start = m.end()
            else:
                i += 1
        else:
            i += 1
    flush('code', start, n)
    return out


def rename_text(text, mapping, counts=None):
    parts = []
    for kind, chunk in segments(text):
        if kind == 'lit':
            parts.append(chunk)
            continue

        def sub(m):
            t = m.group(0)
            if t in mapping:
                if counts is not None:
                    counts[t] += 1
                return mapping[t]
            return t
        parts.append(IDENT.sub(sub, chunk))
    return ''.join(parts)


def tag_definitions(text, new_names, tagged):
    """Put TAG on the definition line of each class in new_names, a dict class -> confidence (`class X` /
    `struct X` not ending in `;`)."""
    lines = text.split('\n')
    for i, ln in enumerate(lines):
        m = re.match(r'\s*(?:class|struct)\s+(?:[A-Z_]+\s+)?([A-Za-z_][A-Za-z0-9_]*)\b(?!\s*;)', ln)
        if not m or m.group(1) not in new_names:
            continue
        body = ln.rstrip('\r')
        cr = ln[len(body):]
        code = body.split('//', 1)[0].rstrip()
        if code.endswith(';') and '{' not in code:
            continue                                   # a forward declaration with a trailing comment
        name = m.group(1)
        TAG = globals()['TAG'] % new_names[name]
        t = NAME_TAG.search(body)
        if t:
            body = body[:t.start()].rstrip() + '  ' + TAG
        elif '//' in body:
            cut = body.index('//')
            body = body[:cut].rstrip() + '  ' + TAG + '; ' + body[cut + 2:].strip()
        else:
            prev = lines[i - 1] if i else ''
            pt = NAME_TAG.search(prev)
            if pt and prev.lstrip().startswith('//'):
                pb = prev.rstrip('\r')
                pcr = prev[len(pb):]
                old = pb[pt.start() + 2:].strip()
                lines[i - 1] = pb[:pt.start()] + TAG + '; before the rename ' + old + pcr
            else:
                body = body.rstrip() + '  ' + TAG
        lines[i] = body + cr
        tagged[name] += 1
    return '\n'.join(lines)


def stringizing_macros():
    """Names of macros in the source trees whose body stringizes or pastes a parameter (# or ##)."""
    names = set()
    pat = re.compile(r'^[ \t]*#[ \t]*define[ \t]+([A-Za-z_][A-Za-z0-9_]*)\(([^)]*)\)((?:[^\n\\]|\\\r?\n|\\.)*)', re.M)
    for p in source_files():
        text = io.open(p, encoding='latin-1', newline='').read()
        if '#' not in text:
            continue
        for m in pat.finditer(text):
            if re.search(r'(?<!#)#(?!#)\s*[A-Za-z_]|##', m.group(3)):
                names.add(m.group(1))
    return names


def macro_uses(text, macros, old_names):
    """(macro, class) for every old class name inside the argument list of a stringizing / pasting macro."""
    hits = []
    for m in re.finditer(r'\b([A-Za-z_][A-Za-z0-9_]*)\s*\(', text):
        if m.group(1) not in macros:
            continue
        depth, j = 1, m.end()
        while j < len(text) and depth:
            depth += {'(': 1, ')': -1}.get(text[j], 0)
            j += 1
        for t in IDENT.findall(text[m.end():j]):
            if t in old_names:
                hits.append((m.group(1), t))
    return hits


def rename_symbols(path, mapping, write):
    with io.open(path, encoding='utf-8', newline='') as f:
        raw = f.read()
    changed = [0]

    def sub(m):
        s = m.group(2)
        pre = 'j_' if s.startswith('j_?') else ''       # a thunk row: mangle's pattern needs the name's start
        new = pre + mangle.rename_all(s[len(pre):], mapping)
        if '?' not in s:                               # a plain `Class::Method` name: by identifier
            new = IDENT.sub(lambda t: mapping.get(t.group(0), t.group(0)), s)
        if new != s:
            changed[0] += 1
        return m.group(1) + new + '"'
    # decorated names never hold a quote or a backslash, so the fields are rewritten in the text: the file's
    # formatting stays byte for byte as its tool wrote it
    out = re.sub(r'("(?:symbol|name|replaces)":\s*")([^"\\]*)"', sub, raw)
    json.loads(out)
    if write and out != raw:
        with io.open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(out)
    return changed[0]


def rename_tool_file(path, mapping, write):
    with io.open(path, encoding='utf-8', newline='') as f:
        raw = f.read()
    n = [0]

    def sub(m):
        t = m.group(0)
        if t in mapping:
            n[0] += 1
            return mapping[t]
        return t
    out = IDENT.sub(sub, raw)
    # decorated names inside the tools' strings: the class after ??0 / ??_G / a type code
    out2 = re.sub(r'\?[?A-Za-z0-9_@$]+', lambda m: mangle.rename_all(m.group(0), mapping), out)
    if out2 != out:
        n[0] += 1
    if write and out2 != raw:
        with io.open(path, 'w', encoding='utf-8', newline='') as f:
            f.write(out2)
    return n[0]


def selftest():
    mp = {'Foo': 'Bar', 'GpsClass': 'GPSClass'}
    src = ('#include "Foo.h"\nclass Foo : public Base  // NAME 2: guess\n{\n  Foo(); // Foo "Foo::x" here\n'
           '  const char *s = "Foo"; char c = \'F\'; FooX y; /* Foo */\n};\nclass Foo;\nGpsClass g;\n')
    got = rename_text(src, mp)
    want = ('#include "Foo.h"\nclass Bar : public Base  // NAME 2: guess\n{\n  Bar(); // Bar "Foo::x" here\n'
            '  const char *s = "Foo"; char c = \'F\'; FooX y; /* Bar */\n};\nclass Bar;\nGPSClass g;\n')
    assert got == want, got
    tagged = collections.Counter()
    got = tag_definitions(got, {'Bar': 'A'}, tagged)
    assert 'class Bar : public Base  ' + TAG % 'A' + '\n' in got and 'class Bar;\n' in got and tagged['Bar'] == 1, got
    t2 = tag_definitions('// NAME 3: root "Ship"; structure = X\nclass Bar\n{', {'Bar': 'C'}, tagged)
    assert t2 == TAG % 'C' + '; before the rename NAME 3: root "Ship"; structure = X\nclass Bar\n{', t2
    assert got.count('\n') == src.count('\n')
    assert macro_uses('DECL(Foo, 1); f(Foo);', {'DECL'}, {'Foo'}) == [('DECL', 'Foo')]
    print('classrename self-test passed')


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--write', action='store_true')
    ap.add_argument('--only', help='comma-separated class names (ours)')
    ap.add_argument('--collisions', action='store_true')
    ap.add_argument('--selftest', action='store_true')
    a = ap.parse_args()
    if a.selftest:
        return selftest()

    rows = load_rows()
    only = set(a.only.split(',')) if a.only else None
    if only:
        missing = only - {r['ours'] for r in rows}
        if missing:
            sys.exit('not a keep row: ' + ', '.join(sorted(missing)))

    files = list(source_files())
    texts = {}
    present = collections.Counter()
    in_code = collections.Counter()
    all_names = {r['ours'] for r in rows} | {r['retail'] for r in rows}
    for p in files:
        t = io.open(p, encoding='latin-1', newline='').read()
        texts[p] = t
        for kind, chunk in segments(t):
            if kind != 'lit':
                for tok in IDENT.findall(chunk):
                    if tok in all_names:
                        present[tok] += 1
                        if kind == 'code':
                            in_code[tok] += 1

    ours_set = {r['ours'] for r in rows}
    chosen, left = [], []
    for r in rows:
        o, n = r['ours'], r['retail']
        why = None
        if only is not None:
            if o not in only:
                continue
        elif r['split_suspect'] not in ('0', ''):
            why = 'split suspect'
        elif not present[o]:
            why = 'not spelled in the source'
        elif in_code[n] and not a.collisions:
            why = 'retail name already an identifier in code (%d)' % in_code[n]
        if why:
            left.append((o, n, why))
        else:
            chosen.append(r)
    mapping = {r['ours']: r['retail'] for r in chosen}
    if not mapping:
        sys.exit('nothing to rename (%d rows left out; see --only, --collisions)' % len(left))
    new_count = collections.Counter(mapping.values())
    bad = [n for n, c in new_count.items() if c > 1] + [n for n in mapping.values() if n in ours_set]
    if bad:
        sys.exit('chain or merge, rename these by hand: ' + ', '.join(sorted(set(bad))))

    macros = stringizing_macros()
    counts, tagged = collections.Counter(), collections.Counter()
    per_files = collections.defaultdict(set)
    macro_hits = collections.defaultdict(set)
    changed_files = 0
    new_names = {r['retail']: r['confidence'] for r in chosen}
    for p in files:
        t = texts[p]
        c = collections.Counter()
        out = rename_text(t, mapping, c)
        if not c:
            continue
        rel = os.path.relpath(p, ROOT).replace('\\', '/')
        for mac, cls in macro_uses(t, macros, set(c)):
            macro_hits[cls].add('%s in %s' % (mac, rel))
        out = tag_definitions(out, new_names, tagged)
        assert out.count('\n') == t.count('\n'), rel
        for k, v in c.items():
            counts[k] += v
            per_files[k].add(rel)
        changed_files += 1
        if a.write:
            with io.open(p, 'w', encoding='latin-1', newline='') as f:
                f.write(out)

    sym = {s: rename_symbols(os.path.join(ROOT, s), mapping, a.write) for s in SYMBOL_FILES}
    tool = {}
    for s in TOOL_FILES:
        p = os.path.join(ROOT, s)
        if os.path.exists(p):
            k = rename_tool_file(p, mapping, a.write)
            if k:
                tool[s] = k

    os.makedirs(os.path.join(ROOT, '.work', 'names'), exist_ok=True)
    rep = os.path.join(ROOT, '.work', 'names', 'classrename-report.tsv')
    with io.open(rep, 'w', encoding='utf-8', newline='\n') as f:
        f.write('ours\tretail\toccurrences\tfiles\tdefinitions_tagged\tstringizing_macro_uses\n')
        for r in chosen:
            o = r['ours']
            f.write('%s\t%s\t%d\t%d\t%d\t%s\n' % (o, r['retail'], counts[o], len(per_files[o]), tagged[r['retail']],
                                                  '; '.join(sorted(macro_hits[o]))))
        for o, n, why in left:
            f.write('%s\t%s\t\t\t\tLEFT OUT: %s\n' % (o, n, why))
    untagged = [r['retail'] for r in chosen if not tagged[r['retail']]]
    multi = [n for n, c in tagged.items() if c > 1]
    print('%s: %d classes, %d occurrences in %d source files; %d definitions tagged (%d classes with none, %d with '
          'several)' % ('written' if a.write else 'dry run', len(chosen), sum(counts.values()), changed_files,
                        sum(tagged.values()), len(untagged), len(multi)))
    print('symbol files: ' + ', '.join('%s %d' % kv for kv in sym.items()))
    print('tool files: ' + (', '.join('%s %d' % kv for kv in sorted(tool.items())) or 'none'))
    print('left out: %d (%s)' % (len(left), dict(collections.Counter(w.split(' (')[0] for _, _, w in left))))
    print('classes used in a stringizing / pasting macro: %d' % sum(1 for v in macro_hits.values() if v))
    print('report: ' + os.path.relpath(rep, ROOT))


if __name__ == '__main__':
    main()
