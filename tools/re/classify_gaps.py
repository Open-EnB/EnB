"""Splits a library's gaps into functions the client links (but differ) and ones it probably never linked.

    python classify_gaps.py --gaps ../../docs/data/gaps-wwlib.json --objs DIR [--objs DIR...]

With /Gy and /OPT:REF the linker drops every function nothing references, so most of a library's
"gaps" are simply absent from the client. A gap is LINKED when a function that is in the client
(one proven byte-exact) calls it, or a vtable of a class in the client lists it; or when the gap
locator paired it with a client function at similarity 0.5 or more. Otherwise it is UNREFERENCED:
nothing proven references it, and it is probably not in the client at all.
Writes OUT.md next to the gaps file (gaps-X.json -> gaps-X-classified.md).
"""
import argparse
import collections
import glob
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from objmatch import CoffObject, demangle, match_objects  # noqa: E402
from clientimage import ClientImage  # noqa: E402


def references(objs, in_client):
    """Symbols referenced (called, or put in a vtable) by functions/vtables that are in the client."""
    used = set()
    for p in objs:
        obj = CoffObject(p)
        funcs = obj.functions()
        bysec = collections.defaultdict(list)
        for name, sec, s, e in funcs:
            bysec[sec].append((s, e, name))
        symname = {x['index']: x['name'] for x in obj.symbols}
        for sec, info in enumerate(obj.sections):
            for va, idx, typ in info['relocs']:
                target = symname.get(idx)
                if not target:
                    continue
                owner = next((n for s, e, n in bysec.get(sec, []) if s <= va < e), None)
                if owner and owner in in_client:
                    used.add(target)
        # vtables: count their slots as used when the class has any function in the client
        for s in obj.symbols:
            if s['name'].startswith('??_7') and s['section'] > 0:
                cls = s['name'][4:].split('@@')[0]
                if any(cls in n for n in in_client if '@' + cls + '@' in n or n.startswith('??0' + cls)):
                    sec = obj.sections[s['section'] - 1]
                    for va, idx, typ in sec['relocs']:
                        if symname.get(idx):
                            used.add(symname[idx])
    return used


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--gaps', required=True)
    ap.add_argument('--objs', action='append', required=True)
    a = ap.parse_args()
    img = ClientImage()
    objs = [p for d in a.objs for p in sorted(glob.glob(os.path.join(d, '*.obj')))]
    in_client = {r['symbol'] for r in match_objects(img, objs) if r['status'] in ('exact', 'multiple')}
    used = references(objs, in_client)
    rows = json.load(open(a.gaps))
    linked, unref = [], []
    for g in rows:
        sym = g.get('symbol') or ''
        if sym in used or (g.get('similarity') or 0) >= 0.5:
            linked.append(g)
        else:
            unref.append(g)
    out = a.gaps.replace('.json', '-classified.md')
    title = os.path.basename(a.gaps).replace('gaps-', '').replace('.json', '')
    with open(out, 'w', newline='\n', encoding='utf-8') as f:
        f.write(f'# {title}: gaps classified (generated by tools/re/classify_gaps.py)\n\n'
                f'{len(linked)} linked but different (referenced by code proven to be in the client, or '
                f'paired with a client function at similarity >= 0.5): these are E&B changes to reconstruct. '
                f'{len(unref)} unreferenced: nothing proven references them; with /OPT:REF they are '
                f'probably not in the client.\n\n## Linked but different\n\n'
                '| Object | Function | Length | Client | Similarity |\n|---|---|---|---|---|\n')
        for g in sorted(linked, key=lambda g: -(g.get('similarity') or 0)):
            f.write(f"| {g['object']} | `{g['function'][:60]}` | {g['length']} | {g.get('address') or '-'} | {g.get('similarity')} |\n")
        f.write('\n## Unreferenced (probably not linked)\n\n')
        f.write(', '.join(f"`{g['function'][:50]}`" for g in unref) + '\n')
    print(f'{title}: {len(linked)} linked, {len(unref)} unreferenced -> {out}')


if __name__ == '__main__':
    main()
