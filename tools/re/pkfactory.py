"""Map the packet factory's switch (app\\packets\\pk.cpp 0x869790, docs/kernel-map.md 5) to a table.

    python tools/re/pkfactory.py [--out docs/data/packet-factory.txt]

For each opcode the switch handles: the bytes it news, the constructor it calls with the raw
message (incremental-link thunks followed), the vtable that constructor stores last (the packet
class's own), and the opcode's name from the reference decoder's the Net-7 opcode table. The switch's shape is
the client's: opcodes 0-237 through the table 0x86D1CC, 5000 alone, 5001-5011 through 0x86D584,
30000 alone, 30001-30027 through the byte index 0x86D5F0 and the table 0x86D5B0; everything else
reaches the default 0x86D19F (assert line 1078). Generated: don't hand-edit the output.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from clientimage import ClientImage  # noqa: E402

ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
OPCODES = os.path.join(os.path.dirname(ROOT), 'the reference decoder', 'src', 'Shared', 'the reference protocol table', 'the Net-7 opcode table')
DEFAULT = 0x86D19F
NEW = 0x4E9CB0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'docs', 'data', 'packet-factory.txt'))
    a = ap.parse_args()
    ci = ClientImage()
    th = ci.incremental_thunks()
    names = {}
    if os.path.exists(OPCODES):
        for m in re.finditer(r'\[0x([0-9A-Fa-f]+)\]\s*=\s*"([^"]+)"', open(OPCODES, encoding='utf-8').read()):
            names[int(m.group(1), 16)] = m.group(2)

    cases = {}
    for op in range(0, 0xEE):
        cases[op] = ci.u32(0x86D1CC + 4 * op)
    cases[5000] = 0x86CD03
    for i in range(11):
        cases[5001 + i] = ci.u32(0x86D584 + 4 * i)
    cases[30000] = 0x86CED2
    for i in range(0x1B):
        idx = ci.data[ci.offset(0x86D5F0 + i)]
        cases[30001 + i] = ci.u32(0x86D5B0 + 4 * idx)

    def resolve(t):
        return th.get(t, t)

    def ctor_vtable(ctor):
        last = None
        for ins in ci.disasm(ctor, 0x300):
            if ins.mnemonic == 'mov' and ins.op_str.startswith('dword ptr [') and ', 0x' in ins.op_str:
                v = int(ins.op_str.rsplit(', ', 1)[1], 16)
                if 0xAD0000 <= v < 0xBA0000:
                    last = v
            if ins.mnemonic == 'ret':
                break
        return last

    rows = []
    for op in sorted(cases):
        t = cases[op]
        if t == DEFAULT:
            continue
        size = ctor = inline_vt = None
        prev_push = None
        seen_new = False
        for ins in ci.disasm(t, 0x80):
            if ctor and ins.mnemonic in ('ret', 'jmp'):
                break
            if ctor and ins.mnemonic == 'mov' and ins.op_str.startswith('dword ptr [') \
                    and '+' not in ins.op_str.split(']')[0] and ', 0x' in ins.op_str:
                v = int(ins.op_str.rsplit(', ', 1)[1], 16)
                if 0xAD0000 <= v < 0xBA0000:
                    inline_vt = v
            if ins.mnemonic == 'push' and ins.op_str.startswith('0x'):
                prev_push = int(ins.op_str, 16)
            if ins.mnemonic == 'call' and not ctor:
                target = resolve(int(ins.op_str, 16)) if ins.op_str.startswith('0x') else None
                if not seen_new and target == NEW:
                    size = prev_push
                    seen_new = True
                elif seen_new:
                    ctor = target
        vt = inline_vt or (ctor_vtable(ctor) if ctor else None)
        rows.append((op, size, ctor, vt, names.get(op, '?'), inline_vt is not None))

    shared = {}
    for r in rows:
        shared.setdefault(r[2], []).append(r[0])
    with open(a.out, 'w', newline='\n') as f:
        f.write('# The packet factory 0x869790 (app\\packets\\pk.cpp): generated by tools/re/pkfactory.py, do not edit.\n')
        f.write('# opcode (decimal, hex)  name (the Net-7 opcode table)  bytes  constructor  vtable  [*: the vtable is stored in\n')
        f.write('# the case, after a base constructor: the class\'s own constructor inlined]  (constructor shared with)\n')
        for op, size, ctor, vt, name, inl in rows:
            other = [o for o in shared[ctor] if o != op]
            f.write('%5d 0x%04X  %-32s %-6s %-9s %s%s%s\n' % (
                op, op, name, '0x%X' % size if size else '?', '0x%X' % ctor if ctor else '?',
                '0x%X' % vt if vt else '?', ' *' if inl else '',
                ('  (with %s)' % ', '.join(map(str, other))) if other else ''))
    print('%d opcodes, %d constructors called, %d vtables -> %s' % (
        len(rows), len(shared), len(set(r[3] for r in rows)), a.out))

if __name__ == '__main__':
    main()
