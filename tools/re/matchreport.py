"""Combines objmatch results from several EA copies of one library into a per-file report.

    python matchreport.py --title WWLib --out docs/data/bytematch-wwlib R=renegade.json Z=zerohour.json

For every source file: functions found byte-exact from each copy, and how many client addresses
only one copy explains. Writes OUT.md and OUT.json (client address -> copy, object, function).
"""
import argparse
import collections
import json


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('runs', nargs='+', help='TAG=objmatch.json')
    ap.add_argument('--title', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--flags', default='')
    a = ap.parse_args()
    runs = {}
    for r in a.runs:
        tag, path = r.split('=', 1)
        runs[tag] = json.load(open(path))
    tags = list(runs)

    per_file = collections.defaultdict(lambda: {t: {'exact': 0, 'total': 0, 'addr': set()} for t in tags})
    addr_info = collections.defaultdict(dict)
    for t, results in runs.items():
        for r in results:
            f = per_file[r['object'].lower()][t]
            f['total'] += 1
            if r['status'] == 'exact':
                f['exact'] += 1
                f['addr'].add(r['addresses'][0])
                addr_info[r['addresses'][0]][t] = {'object': r['object'], 'function': r['name'],
                                                    'symbol': r['symbol'], 'length': r['length']}

    with open(a.out + '.json', 'w') as fp:
        json.dump(dict(sorted(addr_info.items())), fp, indent=1)

    with open(a.out + '.md', 'w', encoding='utf-8') as fp:
        fp.write(f'# {a.title}: byte-exact matches (generated by tools/re/matchreport.py)\n\n')
        fp.write('Each EA copy compiled with VC6 SP4' + (f' (`{a.flags}`)' if a.flags else '') +
                 '; every function searched for in client.exe with relocated fields masked '
                 '(tools/re/objmatch.py). Only functions found exactly once are counted.\n\n')
        total = set(addr_info)
        fp.write(f'Client functions explained: **{len(total)}**. ')
        fp.write(', '.join(f'{t}: {sum(1 for v in addr_info.values() if t in v)}' for t in tags))
        only = {t: sum(1 for v in addr_info.values() if list(v) == [t]) for t in tags}
        fp.write('; found only in ' + ', '.join(f'{t}: {n}' for t, n in only.items()) + '.\n\n')
        fp.write('| File | ' + ' | '.join(f'{t} exact/functions' for t in tags) + ' | ' +
                 ' | '.join(f'only {t}' for t in tags) + ' |\n')
        fp.write('|---|' + '---|' * (2 * len(tags)) + '\n')
        for name in sorted(per_file):
            row = per_file[name]
            cells = [f"{row[t]['exact']}/{row[t]['total']}" if row[t]['total'] else '-' for t in tags]
            onl = []
            for t in tags:
                others = set().union(*(row[o]['addr'] for o in tags if o != t))
                onl.append(str(len(row[t]['addr'] - others)))
            fp.write(f'| {name} | ' + ' | '.join(cells) + ' | ' + ' | '.join(onl) + ' |\n')
    print(f'{len(addr_info)} client functions; ' + ', '.join(f'only {t}: {n}' for t, n in only.items()))


if __name__ == '__main__':
    main()
