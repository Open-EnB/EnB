"""Which EA copy of each shared library file is closest to the one linked into client.exe.

For every source file that exists in more than one EA copy (Renegade R, Generals G, Zero Hour Z),
counts the file's strings found in the client, and lists the strings only one copy has. A string
only one copy has, found in the client, says the client's file descends from that copy.

    python libversions.py [--client PATH]     -> docs/data/library-versions.md
"""
import argparse
import collections
import os

from clientimage import ClientImage, DEFAULT_CLIENT
from easource import LIBRARIES, strings_by_function, walk_library

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.normpath(os.path.join(HERE, '..', '..', 'docs', 'data', 'library-versions.md'))
MIN_LEN = 6


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--client', default=DEFAULT_CLIENT)
    args = ap.parse_args()
    client = set(ClientImage(args.client).strings(4).values())

    files = collections.defaultdict(dict)  # (lib, file) -> tag -> set(strings)
    for tag, path, lib in LIBRARIES:
        for rel, full in walk_library(path):
            strs = set()
            for s in strings_by_function(full).values():
                strs |= {x for x in s if len(x) >= MIN_LEN}
            files[(lib, rel.lower())][tag] = strs

    rows, votes = [], collections.defaultdict(collections.Counter)
    for (lib, rel), copies in sorted(files.items()):
        hits = {t: s & client for t, s in copies.items()}
        if not any(hits.values()):
            continue
        only = {}
        for t, h in hits.items():
            others = set().union(*(hits[o] for o in hits if o != t)) if len(hits) > 1 else set()
            # A string the other copies have in their source but the client lacks also counts
            # against them; here we only list positive evidence.
            only[t] = sorted(h - others)
        for t, o in only.items():
            if o and len(copies) > 1:
                votes[lib][t] += len(o)
        rows.append((lib, rel, {t: len(h) for t, h in hits.items()}, {t: len(s) for t, s in copies.items()}, only))

    with open(OUT, 'w', newline='\n', encoding='utf-8') as f:
        f.write('# Library versions: which EA copy client.exe follows (generated by tools/re/libversions.py)\n\n')
        f.write('R = Renegade (2002), G = Generals (2003), Z = Zero Hour (2003). Hits: strings of that copy\'s '
                'file found in client.exe, out of its strings of 6+ characters. "only" = strings found in the '
                'client that the other copies lack: evidence the client descends from that copy.\n\n')
        f.write('## Votes per library\n\n| Library | ' + ' | '.join('RGZ') + ' |\n|---|---|---|---|\n')
        for lib in sorted(votes):
            f.write(f'| {lib} | ' + ' | '.join(str(votes[lib][t]) for t in 'RGZ') + ' |\n')
        f.write('\n## Per file\n\n| Library | File | R | G | Z | Copy-specific strings found in the client |\n'
                '|---|---|---|---|---|---|\n')
        for lib, rel, hits, totals, only in rows:
            cell = lambda t: f'{hits[t]}/{totals[t]}' if t in hits else '-'
            ev = '<br>'.join(f'{t}: ' + ', '.join('`' + s.replace('|', '/').replace('\r', '').replace('\n', ' ')[:50] + '`'
                                                  for s in o[:4]) + (f' (+{len(o) - 4})' if len(o) > 4 else '')
                             for t, o in only.items() if o and len(totals) > 1)
            f.write(f'| {lib} | {rel} | {cell("R")} | {cell("G")} | {cell("Z")} | {ev} |\n')
    print(f'{len(rows)} files with hits -> {OUT}')
    for lib in sorted(votes):
        print(f'  {lib:12s} ' + ' '.join(f'{t}={votes[lib][t]}' for t in 'RGZ'))


if __name__ == '__main__':
    main()
