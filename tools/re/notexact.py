"""NOT EXACT tracker (decision D64).

Scans the committed E&B code (app/, stubs/, programs/, tests/; the files names.py scans) for
comments that say a function or file is not byte-exact: `// NOT EXACT: why`, also written as
`functional (NOT EXACT: why)` or inside a block comment. Writes docs/data/not-exact.md: per
marker the file and line, the function it belongs to (best effort), and the comment text.

Function attribution: a marker in a comment at column 0 belongs to the next function signature
(a column-0 line with a parenthesis that is not a declaration), unless the comment says "the whole
file" (then the file); a marker at the end of a code line, or in an indented comment, belongs to
the function above it (the last column-0 signature). `?` when none is found within reach.

    python tools/re/notexact.py            # rewrite docs/data/not-exact.md
    python tools/re/notexact.py --print    # print the list instead
"""
import argparse
import os
import re

import names

ROOT = names.ROOT
OUT = os.path.join(ROOT, 'docs', 'data', 'not-exact.md')

MARK = re.compile(r'NOT EXACT\b')
SIG = re.compile(r'^[A-Za-z_~][^;{}=]*\(')                # a function signature line, at column 0
NOT_SIG = re.compile(r'^(typedef|extern|return|if|for|while|switch|else|#|using|class|struct|enum)\b')
REACH = 80                                               # lines to look ahead for a signature
WHOLE = re.compile(r'whole file', re.I)


def signature_name(line):
    """`Class::Method` (or the function name) from a signature line."""
    head = line.split('(')[0]
    m = re.search(r'([A-Za-z_~][\w]*(?:::~?[\w]+|::operator\s*[^\s(]+)*)\s*$', head.rstrip())
    return m.group(1) if m else head.strip()


def is_sig(line):
    return bool(SIG.match(line)) and not NOT_SIG.match(line) and not line.rstrip().endswith(',')


def comment_text(lines, i, start):
    """The marker's text: from NOT EXACT to the end of the line, plus the comment lines that follow."""
    text = lines[i][start:].strip()
    in_line_comment = lines[i].lstrip().startswith('//') or '//' in lines[i][:start]
    j = i + 1
    while j < len(lines) and j < i + 6:
        s = lines[j].strip()
        if in_line_comment and s.startswith('//') and not MARK.search(s):
            text += ' ' + s[2:].strip()
        elif not in_line_comment and s and not s.startswith('*/') and not s.startswith('**/') \
                and (s.startswith('*') or s.startswith('**')) and not MARK.search(s):
            text += ' ' + s.lstrip('*').strip()
        else:
            break
        j += 1
    text = re.sub(r'\s+', ' ', text.rstrip('*/ ').strip())
    return text[:400] + ('...' if len(text) > 400 else '')


def scan(path):
    raw = open(os.path.join(ROOT, path), 'rb').read().decode('utf-8', errors='replace')
    lines = raw.splitlines()
    out = []
    last_sig = None
    sig_at = {}
    for i, line in enumerate(lines):
        if is_sig(line):
            last_sig = signature_name(line)
        sig_at[i] = last_sig
    for i, line in enumerate(lines):
        m = MARK.search(line)
        if not m:
            continue
        text = comment_text(lines, i, m.start())
        col0_comment = line.startswith(('//', '/*', '**', '*'))
        if WHOLE.search(line) or WHOLE.search(text[:120]):
            fn = '(whole file)'
        elif col0_comment:
            fn = '?'
            for j in range(i + 1, min(len(lines), i + REACH)):
                if is_sig(lines[j]):
                    fn = signature_name(lines[j])
                    break
            if fn == '?' and sig_at.get(i):
                fn = sig_at[i]
        else:
            fn = sig_at.get(i) or '?'
        form = 'marker' if re.search(r'//\s*NOT EXACT\b', line) else 'mention'
        out.append((path, i + 1, fn, form, text))
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--print', action='store_true', help='print instead of writing the file')
    args = ap.parse_args()
    rows = []
    for path in names.tracked_files():
        rows += scan(path)
    rows.sort(key=lambda r: (r[0], r[1]))
    files = len({r[0] for r in rows})
    out = ['# Code marked NOT EXACT (generated by tools/re/notexact.py)', '',
           'Every comment in the committed code that says a function or file is not byte-exact',
           '(decision D64): functional rewrites, inlined library code that differs, a compiler choice',
           'not reproduced. `marker` = a `// NOT EXACT:` comment, `mention` = the words inside a longer',
           'comment. The function is the next signature after a comment at column 0, otherwise the one',
           'above the line (best effort: check the line). Regenerate with `python tools/re/notexact.py`;',
           'edit the comments in the code, not this file.', '',
           '%d entries in %d files.' % (len(rows), files), '',
           '| File:line | Function | Form | Comment |', '|---|---|---|---|']
    for path, line, fn, form, text in rows:
        out.append('| `%s:%d` | `%s` | %s | %s |' % (path, line, fn, form, text.replace('|', '\\|')))
    if not rows:
        out.append('| | (none) | | |')
    text = '\n'.join(out) + '\n'
    if args.print:
        print(text)
    else:
        open(OUT, 'w', encoding='utf-8', newline='\n').write(text)
        print('%s: %d entries in %d files' % (os.path.relpath(OUT, ROOT), len(rows), files))


if __name__ == '__main__':
    main()
