"""Makes mss32.lib, the Miles import library, from the game's own Mss32.dll (D51, L2).

    python tools/vc6/mkmss32.py def [--dll PATH]       write tools/vc6/mss32.def from the DLL's exports
    python tools/vc6/mkmss32.py lib [--out DIR]         build DIR/mss32/mss32.lib (default build/) in a VM

`def` lists every name Mss32.dll exports, exactly as exported (the stdcall ones decorated:
`_AIL_startup@0`, `_AIL_open_stream_by_sample@16`; fastcall `@stream_background@0`; the cdecl
ones plain), so the import library is exact by construction (docs/toolchain.md "Miles fixes" 1).

`lib`: VC6's `lib /def` cannot turn that .def into a working import library. It reads every
.def name as an undecorated C name and writes the import with name type "no prefix": the entry
`AIL_shutdown@0` gives the symbol `_AIL_shutdown@0` but imports `AIL_shutdown@0`, which the DLL
does not export, and `_AIL_startup@0` gives the symbol `__AIL_startup@0` (tested 2026-10-24, with
`internal=external` aliases too). So `lib` writes a stub DLL source from the .def, one empty
`__declspec(dllexport)` function per export with the right calling convention and argument
bytes, and links it as `Mss32.dll` (/noentry): the import library LINK writes beside it imports
each name with name type "name", i.e. exactly as exported. The stub DLL is discarded.

The SDK's mss32.lib also carries one static member, `MSS_auto_cleanup` (the client has it at
0xA03A30, just before the Miles thunks: `atexit` of a wrapper that calls `AIL_shutdown`, then
`return 0`); `lib` compiles that from the source below and adds it to the library.
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
DLL = os.path.join(os.environ.get('ENB_RETAIL_INSTALL') or r'C:\Program Files (x86)\EA GAMES\Earth & Beyond',
                   'release', 'Mss32.dll')
DEF = os.path.join(HERE, 'mss32.def')

AUTO_CLEANUP = r'''/* MSS_auto_cleanup: the static member of RAD's mss32.lib (client 0xA03A30). mss.h's
   AIL_startup() macro calls it first; it registers AIL_shutdown to run at exit. */
#include <stdlib.h>
__declspec(dllimport) void __stdcall AIL_shutdown(void);
static void __cdecl MSS_shutdown_at_exit(void) { AIL_shutdown(); }
int __cdecl MSS_auto_cleanup(void)
{
	atexit(MSS_shutdown_at_exit);
	return 0;
}
'''


def write_def(dll):
    import pefile
    pe = pefile.PE(dll, fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY['IMAGE_DIRECTORY_ENTRY_EXPORT']])
    names = sorted(e.name.decode() for e in pe.DIRECTORY_ENTRY_EXPORT.symbols if e.name)
    lines = ['; Generated by tools/vc6/mkmss32.py def from the game\'s Mss32.dll exports (D51).',
             '; Names exactly as exported. Build with `mkmss32.py lib` (VC6 lib /def cannot: see the script).',
             'LIBRARY Mss32.dll', 'EXPORTS'] + [f'  {n}' for n in names]
    open(DEF, 'w', newline='\r\n').write('\n'.join(lines) + '\n')
    print(f'{DEF}: {len(names)} exports')


STD = re.compile(r'^_(\w+)@(\d+)$')
FAST = re.compile(r'^@(\w+)@(\d+)$')


def stub_source():
    names = [l.strip() for l in open(DEF) if l.startswith('  ')]
    out = ['/* Generated by tools/vc6/mkmss32.py: an empty export per Mss32.dll name, only so that',
           '   LINK writes an exact import library. Never run. */']
    for n in names:
        m = STD.match(n) or FAST.match(n)
        if m:
            conv = '__stdcall' if n.startswith('_') else '__fastcall'
            k = int(m.group(2)) // 4
            args = ', '.join(f'int a{i}' for i in range(k)) or 'void'
            out.append(f'__declspec(dllexport) int {conv} {m.group(1)}({args}) {{ return 0; }}')
        elif re.fullmatch(r'[A-Za-z_]\w*', n):
            out.append(f'__declspec(dllexport) int __cdecl {n}(void) {{ return 0; }}')
        else:
            raise SystemExit(f'unexpected export name {n}')
    return '\n'.join(out) + '\n', len(names)


def build_lib(out):
    import vc6
    d = os.path.join(out, 'mss32')
    os.makedirs(d, exist_ok=True)
    src, n = stub_source()
    open(os.path.join(d, 'mss32_stub.c'), 'w', newline='\r\n').write(src)
    open(os.path.join(d, 'mss_auto_cleanup.c'), 'w', newline='\r\n').write(AUTO_CLEANUP)
    w = vc6.WORK + '\\mkmss32'
    vc6.run_bat([f'if exist "{w}" rmdir /s /q "{w}"', f'mkdir "{w}"'])
    for f in ('mss32_stub.c', 'mss_auto_cleanup.c'):
        vc6.scp(os.path.join(d, f), vc6.remote(w + '\\' + f))
    p = vc6.run_bat([
        f'cd /d "{w}"',
        'cl /nologo /c /O1 mss32_stub.c > build.log 2>&1',
        'link /nologo /dll /noentry /nodefaultlib /machine:ix86 /out:Mss32.dll /implib:mss32imp.lib mss32_stub.obj >> build.log 2>&1',
        'cl /nologo /c /MT /O2 mss_auto_cleanup.c >> build.log 2>&1',
        'lib /nologo /out:mss32.lib mss32imp.lib mss_auto_cleanup.obj >> build.log 2>&1',
        'dumpbin /headers mss32.lib > headers.txt 2>&1',
        'dumpbin /linkermember:1 mss32.lib > linkermember.txt 2>&1',
    ])
    for f in ('mss32.lib', 'build.log', 'headers.txt', 'linkermember.txt'):
        vc6.scp(vc6.remote(w + '\\' + f), os.path.join(d, f))
    vc6.ssh(f'cmd /c rmdir /s /q "{w}"', check=False)
    hdr = open(os.path.join(d, 'headers.txt'), encoding='latin1').read()
    exact = len(re.findall(r'Name type\s*:\s*name', hdr))
    print(f'{d}\\mss32.lib: {n} exports, {exact} imported by exact name; build.log:')
    print(open(os.path.join(d, 'build.log'), encoding='latin1').read().strip()[-800:])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('command', choices=['def', 'lib'])
    ap.add_argument('--dll', default=DLL)
    ap.add_argument('--out', default=os.path.join(REPO, 'build'))
    a = ap.parse_args()
    if a.command == 'def':
        write_def(a.dll)
    else:
        build_lib(a.out)


if __name__ == '__main__':
    main()
