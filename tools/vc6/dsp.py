"""Generates the VC6 workspace: app\\main\\main.dsw with one .dsp per library and the exe projects (D248).

    python tools/vc6/dsp.py generate
    python tools/vc6/dsp.py list                 the projects, their files and configurations
    python tools/vc6/dsp.py clean                delete the generated files

Every .dsp / .dsw is written from the same tables build.py and verify use (libdefs.py: LIB_FLAGS,
FILE_FLAGS, APP_LIBS, tree_includes, NOT_LINKED; build.py: the committed sources, PROGRAMS, LINK_SYS),
so a project's compile lines are build.py's. They are generated, never edited and never committed
(.gitignore): a new source file is in the next generation, and parallel builders do not merge them.

The layout is a written-down guess at Westwood's (docs/build-your-own.md "How the workspace is laid
out"), from the client's evidence and Renegade's commando.dsw:
* the client's PDB path `e:\\build\\beta\\G\\app\\main\\client_release\\main.pdb`: an exe project
  `main` in app\\main, configuration `client_release`; every project here has that one
  configuration, so a workspace build picks it for each dependency;
* the client's __FILE__ strings `e:\\build\\beta\\G\\app\\...` and `...\\G\\libs\\wwonline\\wnet\\...`:
  the tree is opened in the VM through build.py's alias (vc6._alias_setup: E: a subst, the repository a
  junction at E:\\build\\beta\\G), so cl is given the same path the client's strings hold;
* Renegade: one static library project per library directory, the exe's LINK32 line listing the .libs.
  E&B's app is split the same way, one library per app\\<folder> (app\\main's own two files are the exe's
  sources); the folder grouping is the guess, the objects are build.py's.
Projects: the EA libraries (LIBS), the app folders' libraries and `main`, the exe: the IDE's build of the one
client build (build.py's `link --program client`: the original sources and every library, no stand-in, no
/force:unresolved; its libraries in PROGRAMS['client']'s link order). CLIENT_PROJECT names it for callers.

The exact workspace app\\main\\exact\\main.dsw (the user, 2026-11-27): the IDE's build of build.py's `client-exact`.
Its `main` lists every object's source itself, in retail's object order (build.exact_order: the IDE links a
project's objects in its file order, a library's members only by LINK's walk), with the EA libraries as
dependencies, retail's library order, /debug /incremental:yes /fixed:no, retail's PDB path (through the alias
E:\\build\\beta\\G, the repository: the PDB lands in app\\main\\client_release, the project's output folder) and
retail's resources. Its inputs come from build.py: build\\res\\client.res and build\\mss32\\exact\\mss32.lib (the long
import format once a `build.py link --program client-exact` has run).
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
import build as B  # noqa: E402
import libdefs as L  # noqa: E402
import vc6  # noqa: E402

BS = chr(92)
CONFIG = 'client_release'
WORKSPACE = os.path.join('app', 'main', 'main.dsw')
GENERATED_BANNER = 'Generated by tools/vc6/dsp.py: do not edit (D248)'
SDK_LIB = B.SDK_LIB
MAIN_DIR = os.path.join('app', 'main')
CLIENT_PROJECT = 'main'      # the exe project: the client (app\main\client_release\client.exe, client.map)
CLIENT_PROGRAM = 'client'    # build.py's PROGRAMS entry whose libraries and system libraries the exe links
EXACT_DIR = os.path.join('app', 'main', 'exact')
EXACT_WORKSPACE = os.path.join(EXACT_DIR, 'main.dsw')


def rel(path, start):
    """`path` relative to the directory `start`, backslashes, as the IDE writes it (.\\x.cpp)."""
    r = os.path.relpath(os.path.join(REPO, path) if not os.path.isabs(path) else path,
                        os.path.join(REPO, start) if not os.path.isabs(start) else start)
    if os.path.isabs(r) or r.startswith(('C:', 'c:')):
        return r
    r = r.replace('/', BS)
    if r == '.':
        return r
    return r if r.startswith('..') else '.' + BS + r


def inc_path(d, start):
    """An include directory: absolute, the real path, as build.py gives it to cl. Not relative, which
    would reach the headers through the alias: cl's internal state then differs (the header names it
    records), and so does the code of a file whose tie-breaks follow it (aux_roots.cpp, workflow.md
    "aux_roots.cpp's SYMBOL_PAD"); measured 2026-11-16 with objcmp.py."""
    return os.path.abspath(d)


def repo_rel(path):
    return os.path.relpath(path, REPO).replace(BS, '/')


class Project:
    def __init__(self, name, directory, kind, sources, flags, defines, includes, file_flags=None,
                 file_defines=None, deps=(), link=None, headers=(), ordered=False, out_dir=None):
        self.name = name
        self.dir = directory              # repository-relative directory holding the .dsp
        self.kind = kind                  # 'lib' or 'exe'
        self.sources = sources            # repository-relative paths (/)
        self.flags = flags
        self.defines = defines
        self.includes = includes          # absolute directories
        self.file_flags = file_flags or {}    # source -> (flags, defines) where a file differs
        self.deps = list(deps)
        self.link = link or []            # exe: LINK32 inputs and options
        self.headers = list(headers)
        self.ordered = ordered            # sources in their given order, one group (the exact project's link order)
        self.out_dir = out_dir or CONFIG

    @property
    def dsp(self):
        return os.path.join(self.dir, self.name + '.dsp')

    def tokens(self, flags, defines):
        """cl options as tokens, /D "X" and /I "X" each one token, /nologo /c dropped (the IDE adds /c)."""
        out = []
        parts = flags.split()
        i = 0
        while i < len(parts):
            if parts[i] in ('/D', '/I') and i + 1 < len(parts):
                out.append(f'{parts[i]} "{parts[i + 1].strip(chr(34))}"')
                i += 2
                continue
            if parts[i] not in ('/c',):
                out.append(parts[i])
            i += 1
        out += [f'/I "{inc_path(d, self.dir)}"' for d in self.includes]
        out += [f'/D "{d}"' for d in defines]
        seen = []
        for x in out:
            if x not in seen:
                seen.append(x)
        return seen

    def cpp_line(self, flags, defines):
        return ' '.join(self.tokens(flags, defines)) + ' /c'

    def file_lines(self, flags, defines):
        """A file's own `# ADD CPP` / `# SUBTRACT CPP` against the project's line."""
        mine = self.tokens(self.flags, self.defines)
        theirs = self.tokens(flags, defines)
        add = [x for x in theirs if x not in mine]
        sub = [x for x in mine if x not in theirs]
        return (['# ADD CPP ' + ' '.join(add)] if add else []) + (['# SUBTRACT CPP ' + ' '.join(sub)] if sub else [])

    def text(self):
        targ = ('"Win32 (x86) Static Library" 0x0104' if self.kind == 'lib'
                else '"Win32 (x86) Application" 0x0101')
        base = 'Win32 (x86) Static Library' if self.kind == 'lib' else 'Win32 (x86) Application'
        cfg = f'{self.name} - Win32 {CONFIG}'
        o = [f'# Microsoft Developer Studio Project File - Name="{self.name}" - Package Owner=<4>',
             '# Microsoft Developer Studio Generated Build File, Format Version 6.00',
             '# ** DO NOT EDIT **', '',
             f'# TARGTYPE {targ}', '',
             f'CFG={cfg}',
             '!MESSAGE This is not a valid makefile. To build this project using NMAKE,',
             '!MESSAGE use the Export Makefile command and run',
             '!MESSAGE ',
             f'!MESSAGE NMAKE /f "{self.name}.mak".',
             '!MESSAGE ',
             '!MESSAGE You can specify a configuration when running NMAKE',
             '!MESSAGE by defining the macro CFG on the command line. For example:',
             '!MESSAGE ',
             f'!MESSAGE NMAKE /f "{self.name}.mak" CFG="{cfg}"',
             '!MESSAGE ',
             '!MESSAGE Possible choices for configuration are:',
             '!MESSAGE ',
             f'!MESSAGE "{cfg}" (based on "{base}")',
             '!MESSAGE ', '',
             f'# {GENERATED_BANNER}',
             '# Begin Project',
             '# PROP AllowPerConfigDependencies 0',
             '# PROP Scc_ProjName ""',
             '# PROP Scc_LocalPath ""',
             'CPP=cl.exe',
             'RSC=rc.exe', '',
             '# PROP Use_MFC 0',
             '# PROP Use_Debug_Libraries 0',
             f'# PROP Output_Dir "{self.out_dir}"',
             f'# PROP Intermediate_Dir "{CONFIG}"',
             '# PROP Target_Dir ""',
             f'# ADD CPP {self.cpp_line(self.flags, self.defines)}',
             '# ADD RSC /l 0x409',
             'BSC32=bscmake.exe',
             '# ADD BSC32 /nologo']
        if self.kind == 'lib':
            o += ['LIB32=link.exe -lib', f'# ADD LIB32 /nologo /out:"{CONFIG}{BS}{self.name}.lib"']
        else:
            o += ['LINK32=link.exe', '# ADD LINK32 ' + ' '.join(self.link)]
        o += ['', '# Begin Target', '', f'# Name "{cfg}"']
        groups = {}
        for s in self.sources:
            d = '' if self.ordered else os.path.dirname(s)
            groups.setdefault(d, []).append(s)
        for d in sorted(groups, key=lambda x: (x != self.dir.replace(BS, '/'), x.lower())):
            name = 'Source' if d in ('', self.dir.replace(BS, '/')) else d
            o += [f'# Begin Group "{name}"', '', '# PROP Default_Filter "cpp;c"']
            for s in (groups[d] if self.ordered else sorted(groups[d], key=str.lower)):
                o += ['# Begin Source File', '', f'SOURCE={rel(s, self.dir)}']
                if s in self.file_flags:
                    o += self.file_lines(*self.file_flags[s])
                o += ['# End Source File']
            o += ['# End Group']
        if self.headers:
            o += ['# Begin Group "Headers"', '', '# PROP Default_Filter "h;hpp;inl"']
            for h in sorted(self.headers, key=str.lower):
                o += ['# Begin Source File', '', f'SOURCE={rel(h, self.dir)}', '# End Source File']
            o += ['# End Group']
        o += ['# End Target', '# End Project', '']
        return '\r\n'.join(o)


def headers_in(dirs):
    out = []
    for d in dirs:
        full = os.path.join(REPO, d)
        out += [repo_rel(os.path.join(full, f)) for f in os.listdir(full) if f.lower().endswith(L.HEADER_EXT)]
    return out


def app_folders():
    """The app's top folders (each a library but main), from the committed sources."""
    tops = sorted({repo_rel(p).split('/')[1] for p in B.sources('app')})
    return [t for t in tops if t != 'main']


def projects():
    incs = L.tree_includes()
    out = []
    ea = []
    for lib in L.LIBS:
        srcs = [repo_rel(p) for p in B.sources(lib)]
        if not srcs:
            continue
        d = L.LIB_TREE.get(lib, lib).replace(BS, '/')    # LIB_TREE is Windows-style; '/' works on both hosts
        ff = {}
        for s in srcs:
            f = L.flags_of(os.path.join(REPO, s))
            if f != L.LIB_FLAGS.get(lib, vc6.DEFAULT_FLAGS):
                ff[s] = (f, vc6.DEFAULT_DEFINES)
        out.append(Project(lib, d, 'lib', srcs, L.LIB_FLAGS.get(lib, vc6.DEFAULT_FLAGS), vc6.DEFAULT_DEFINES,
                           incs, ff, headers=headers_in([d])))
        ea.append(lib)
    app = L.APP_LIBS['app']
    app_srcs = [repo_rel(p) for p in B.sources('app')]
    folder_libs = []
    for top in app_folders():
        srcs = [s for s in app_srcs if s.split('/')[1] == top]
        d = os.path.join('app', top)
        out.append(Project(top, d, 'lib', srcs, L.LIB_FLAGS['app'], app['defines'], incs))
        folder_libs.append(top)
    main_srcs = [s for s in app_srcs if s.split('/')[1] == 'main']
    # the exe's libraries, build.py's link order (PROGRAMS['client']['libs']: app first)
    prog = B.PROGRAMS[CLIENT_PROGRAM]
    lib_order = folder_libs + [l for l in prog.get('libs', B.LINK_LIBS) if l != 'app' and l in ea]
    lib_paths = [rel(os.path.join(REPO, L.LIB_TREE.get(l, l) if l in ea else os.path.join('app', l), CONFIG, l + '.lib'),
                     MAIN_DIR) for l in lib_order]
    extra = [rel(os.path.join(REPO, 'build', B.MSS32), MAIN_DIR), rel(os.path.join(REPO, 'build', B.AUTHLOGIN), MAIN_DIR),
             B.BINKW32_LIB]
    sys_libs = [n.split(':')[-1] for n in B.LINK_SYS] + prog.get('sys', [])
    common = ['/nologo', '/subsystem:windows', '/machine:I386', '/incremental:no', '/nodefaultlib',
              f'/libpath:"{SDK_LIB}"']
    link = [f'"{l}"' for l in lib_paths + extra] + sys_libs + common + \
        [f'/map:"{CONFIG}{BS}client.map"', f'/out:"{CONFIG}{BS}client.exe"']
    out.append(Project(CLIENT_PROJECT, MAIN_DIR, 'exe', main_srcs, L.LIB_FLAGS['app'], app['defines'], incs,
                       deps=folder_libs + ea, link=link))
    return out


def exact_project(incs):
    """The exact workspace's exe (build.py's client-exact): every object's source in retail's order."""
    app = L.APP_LIBS['app']
    by_stem = {}
    for lib, _ in B.EXACT_PICKS:
        for p in B.sources(lib):
            by_stem.setdefault((lib, os.path.splitext(os.path.basename(p))[0].lower()), repo_rel(p))
    srcs, ff = [], {}
    for lib, stem in B.exact_order():
        s = by_stem.get((lib, stem.lower()))
        if not s:
            continue
        srcs.append(s)
        if lib != 'app':
            ff[s] = (L.flags_of(os.path.join(REPO, s)), vc6.DEFAULT_DEFINES)
    prog = B.PROGRAMS['client-exact']
    ea = [l for l in L.LIBS if B.sources(l)]
    libs = [rel(os.path.join(REPO, L.LIB_TREE.get(l, l), CONFIG, l + '.lib'), EXACT_DIR)
            for l in prog.get('libs', B.LINK_LIBS) if l in ea]
    libs += [rel(os.path.join(REPO, 'build', 'mss32', 'exact', 'mss32.lib'), EXACT_DIR),
             rel(os.path.join(REPO, 'build', B.AUTHLOGIN), EXACT_DIR), B.BINKW32_LIB]
    libs += [B.EXACT_SYS_REPLACE.get(n, n).split(':')[-1] for n in B.LINK_SYS] + prog.get('sys', [])

    def key(t):
        n = os.path.basename(t.strip('"').replace(BS, '/')).lower()
        return B.EXACT_LIB_ORDER.index(n) if n in B.EXACT_LIB_ORDER else len(B.EXACT_LIB_ORDER)
    libs = sorted((f'"{l}"' if (BS in l or '/' in l) else l for l in libs), key=key)
    res = rel(os.path.join(REPO, 'build', B.EXACT_RES), EXACT_DIR)
    link = [f'"{res}"'] + libs + \
        ['/nologo', '/subsystem:windows', '/machine:I386', '/nodefaultlib', f'/libpath:"{SDK_LIB}"'] + \
        [f'/pdb:"{B.EXACT_PDB}"' if f.startswith('/pdb:') else f for f in B.EXACT_FLAGS] + \
        [f'/map:"..{BS}{CONFIG}{BS}client-exact.map"', f'/out:"..{BS}{CONFIG}{BS}client-exact.exe"']
    return Project(CLIENT_PROJECT, EXACT_DIR, 'exe', srcs, L.LIB_FLAGS['app'], app['defines'], incs, ff,
                   deps=ea, link=link, ordered=True, out_dir='..' + BS + CONFIG)


def dsw_text(projs, where=MAIN_DIR):
    o = ['Microsoft Developer Studio Workspace File, Format Version 6.00',
         '# WARNING: DO NOT EDIT OR DELETE THIS WORKSPACE FILE!', '',
         f'# {GENERATED_BANNER}', '']
    for p in projs:
        o += ['#' * 79, '', f'Project: "{p.name}"={rel(p.dsp, where)} - Package Owner=<4>', '',
              'Package=<5>', '{{{', '}}}', '', 'Package=<4>', '{{{']
        for d in p.deps:
            o += ['    Begin Project Dependency', f'    Project_Dep_Name {d}', '    End Project Dependency']
        o += ['}}}', '']
    o += ['#' * 79, '', 'Global:', '', 'Package=<5>', '{{{', '}}}', '', 'Package=<3>', '{{{', '}}}', '',
          '#' * 79, '']
    return '\r\n'.join(o)


def generated_files(projs, exact=None):
    return [p.dsp for p in projs] + [WORKSPACE] + ([exact.dsp, EXACT_WORKSPACE] if exact else [])


def write(projs, exact=None):
    written = []
    for p in projs + ([exact] if exact else []):
        path = os.path.join(REPO, p.dsp)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        open(path, 'w', newline='', encoding='latin1').write(p.text())
        written.append(p.dsp)
    open(os.path.join(REPO, WORKSPACE), 'w', newline='', encoding='latin1').write(dsw_text(projs))
    written.append(WORKSPACE)
    if exact:
        # the exact workspace: the EA libraries' projects (the same .dsp files) and its own main
        ea = [p for p in projs if p.name in exact.deps]
        open(os.path.join(REPO, EXACT_WORKSPACE), 'w', newline='', encoding='latin1').write(
            dsw_text(ea + [exact], EXACT_DIR))
        written.append(EXACT_WORKSPACE)
    for f in prune(written):
        print('deleted stale', f)
    return written


def generated_on_disk(root=None):
    """Every .dsp / .dsw under root carrying the generator's banner, as root-relative '/' paths."""
    root = root or REPO
    found = []
    for d, dirs, files in os.walk(root):
        dirs[:] = [x for x in dirs if x not in ('.git', '.work', 'build', CONFIG)]
        for f in files:
            if f.lower().endswith(('.dsp', '.dsw')):
                p = os.path.join(d, f)
                if GENERATED_BANNER in open(p, encoding='latin1').read():
                    found.append(os.path.relpath(p, root).replace(BS, '/'))
    return sorted(found)


def remove_empty_dirs(d, root):
    """Remove d's empty subfolders, then d and its parents while empty (never root or above)."""
    root = os.path.abspath(root)
    d = os.path.abspath(d)
    if not d.startswith(root + os.sep) or not os.path.isdir(d):
        return
    for sub, dirs, files in os.walk(d, topdown=False):
        if not os.listdir(sub):
            os.rmdir(sub)
    while d != root and d.startswith(root + os.sep) and os.path.isdir(d) and not os.listdir(d):
        os.rmdir(d)
        d = os.path.dirname(d)


def prune(keep, root=None):
    """Delete the generated .dsp / .dsw files not in keep (a project the generator no longer makes, such as
    the retired stand-in program's) and the folders that leaves empty; returns the deleted paths."""
    root = root or REPO
    keep = {k.replace(BS, '/') for k in keep}
    gone = []
    for f in generated_on_disk(root):
        if f not in keep:
            p = os.path.join(root, f)
            os.remove(p)
            gone.append(f)
            remove_empty_dirs(os.path.dirname(p), root)
    return gone


def clean(root=None):
    """Delete every generated .dsp / .dsw (found by their banner) and the folders that leaves empty."""
    return prune((), root)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('command', choices=['generate', 'list', 'clean'])
    a = ap.parse_args()
    if a.command == 'clean':
        for f in clean():
            print('deleted', f)
        return
    projs = projects()
    exact = exact_project(L.tree_includes())
    if a.command == 'list':
        for p in projs + [exact]:
            print(f'{p.name:12} {p.kind} {len(p.sources):4} files  {p.dsp}  deps: {len(p.deps)}')
        return
    write(projs, exact)
    print(f'wrote {WORKSPACE} and {len(projs)} projects ({sum(len(p.sources) for p in projs)} source files); '
          f'{EXACT_WORKSPACE} with {len(exact.deps)} library projects and its main ({len(exact.sources)} sources in '
          "retail's object order)")


if __name__ == '__main__':
    main()
