"""Sweep and set SYMBOL_PAD, the symbol pad at the end of app/client/co.cpp (workflow.md 3.3).

Every declaration co.cpp sees moves the aux-data template constructors compiled at its end (auxroots.py's
generated region; aux_roots.cpp until 2026-11-19b, COM) along a cycle of 64 VC6 tie-breaks; each is exact
only in a window. tools/re/auxroots.py's SYMBOL_PAD (an enum of N enumerators) puts the file inside the
windows; retune it when a header co.cpp includes gains or loses declarations.

  auxpad.py sweep [--from 0 --to 63] [--agent NAME] [--host IP | --pool [1]] [--hold | --lockfree]
      compile co.cpp alone with each pad value, print pad -> which of the six
      constructors are exact, and the windows where all six are; --hold takes the importer lock once, at the
      first value, and keeps it to the end (given back on every exit, Ctrl-C included): one wait in the queue;
      --lockfree takes no lock at all (a git worktree on its own leased VM: sendpad.py's lock_free, PAD 2026-11-19b)
  auxpad.py set N
      write SYMBOL_PAD = N in tools/re/auxroots.py and the pad block of co.cpp in place (as sweep does);
      aux_roots.h is not touched (a regeneration is not needed: since 2026-11-18, AB, `auxroots.py generate`
      writes the committed aux_roots.h / co.cpp's region / aux_roots_send.h byte for byte again, the hand edits in its
      HAND_TYPES and the family gates in FAMILY_*; tools/test_auxroots_gen.py checks it)

sweep takes the importer lock per variant (the tree's co.cpp holds the variant only inside it and
is restored after), never for the whole sweep. Every value's exact address set (all of co.cpp's) goes
to .work/log/auxpad-sets.json (--sets PATH) for tools/re/matchaudit.py's pad-held class (D240). VMs: --host IP uses that build VM; otherwise one VM is
leased from pool.py and released at the end (also on failure); --pool says the same (the default, accepted so
that the form the other tools take works here). Measuring logic: HX1's exp.py.
"""
import argparse
import os
import re
import sys

import vc6config

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
AUXROOTS = os.path.join(REPO, 'tools', 're', 'auxroots.py')
CPP = os.path.join(REPO, 'app', 'client', 'co.cpp')
WATCH = ['0x6FB1E0', '0x702240', '0x7045F0', '0x7014B0', '0x701D70', '0x758210']
ENUM = re.compile(r'\r?\n// VC6 symbol pad \(not the client\'s code\): the aux-data constructors.*?\r?\nenum CoSymbolPadType '
                  r'\{[^}]*\};[^\r\n]*\r?\n', re.S)
FILES = ('co', 'aux_roots')     # the ledger keys holding the watched constructors (aux_roots: before COM's move)


def with_pad(text, n):
    """text (co.cpp) with the pad block holding n enumerators (0: no block)."""
    m = ENUM.search(text)
    assert m, 'co.cpp has no symbol pad block (generated by tools/re/auxroots.py)'
    if n == 0:
        return text[:m.start()] + '\n' + text[m.end():]
    block = m.group(0)
    enums = ', '.join(f'CO_PAD_{i:02d}' for i in range(n))
    block = re.sub(r'(enum CoSymbolPadType \{)[^}]*(\};)', lambda k: f'{k.group(1)} {enums} {k.group(2)}', block)
    return text[:m.start()] + block + text[m.end():]


HOLD = False          # --hold: measure() keeps the lock it takes; held_sweep() gives it back


def measure(importer, n, orig):
    """Compile co.cpp with pad n under the importer lock (taken and given back here; with --hold kept)."""
    importer.hold_lock()
    try:
        with open(CPP, 'wb') as f:
            f.write(with_pad(orig.decode('latin-1'), n).encode('latin-1'))
        found, text = importer.compile_and_match([CPP], f'auxpad-{n}')
        got = set().union(*found.values()) if found else set()
        errs = [l for l in text.splitlines() if ' error ' in l][:3]
        return got, errs
    finally:
        with open(CPP, 'wb') as f:
            f.write(orig)
        if not HOLD:
            importer.release_lock()


def windows(ok):
    runs, start, prev = [], None, None
    for n in ok + [None]:
        if start is not None and (n is None or n != prev + 1):
            runs.append((start, prev))
            start = None
        if n is not None and start is None:
            start = n
        prev = n
    return runs


def sweep(a):
    import contextlib
    import importer
    if a.agent:
        importer.set_agent(a.agent)
    if a.lockfree:
        if a.hold:
            raise SystemExit('auxpad: --lockfree takes no lock: --hold makes no sense with it')
        from sendpad import lock_free
        lock_free(REPO)
    if a.host:
        os.environ['ENB_VC6_HOSTS'] = a.host if '@' in a.host else vc6config.CFG['user'] + '@' + a.host
        lease = contextlib.nullcontext()
    else:
        lease = importer.pool_lease(1, a.holder_pid)
    from sendpad import save_sets
    watch = watch_list()
    print(f"watch set from HEAD's ledger (co.cpp's / aux_roots.cpp's of the six): {' '.join(watch)}", flush=True)
    rows, ok, sets, errors = [], [], {}, {}
    with lease:
        for n in range(a.lo, a.hi + 1):
            orig = open(CPP, 'rb').read()          # re-read: the tree may change between variants
            got, errs = measure(importer, n, orig)
            sets[n], errors[n] = got, errs
            save_sets(a.sets, 'app/client/co.cpp', sets, errors, REPO)
            exact = [w for w in watch if w in got]
            line = f'{n:3d}  {len(exact)}/{len(watch)}  ' + ' '.join(w + ('+' if w in got else '-') for w in WATCH) + \
                   f'  total {len(got)}' + (f'  ERRORS {errs}' if errs else '')
            print(line, flush=True)
            rows.append(line)
            if len(exact) == len(watch):
                ok.append(n)
    print(f'\nall {len(watch)} watched exact:', ', '.join(f'{x}..{y}' if x != y else str(x) for x, y in windows(ok))
          or 'none')
    return 0 if ok else 1


def watch_list(src='HEAD'):
    """The six that HEAD's ledger credits to co.cpp or aux_roots.cpp (since SC1 / SI sclient.cpp holds 0x758210 and 0x701D70: a
    sweep watching all six found no window at any value, PAD 2026-11-19b); all six when the ledger has no entry."""
    try:
        import ledger
        files = ledger.load(src, repo=REPO)['app']['files']
        held = {str(x) for k in FILES if k in files for x in files[k]['in_tree']}
    except Exception:
        return list(WATCH)
    return [w for w in WATCH if w in held] or list(WATCH)


def set_pad(a):
    """SYMBOL_PAD = N in tools/re/auxroots.py, and co.cpp's pad block set to N in place. Not a regeneration
    (2026-11-17, AR2: then `auxroots.py generate` wrote an aux_roots.h without the committed file's hand edits, and a
    sendpad.py sweep after `set 33` failed at every value on Type_Name / Value_To_String / String_To_Value(Vector3);
    the generator holds those edits since 2026-11-18, but an in-place edit keeps the window to one file)."""
    with open(AUXROOTS, 'rb') as f:
        src = f.read().decode('utf-8')
    new, k = re.subn(r'^SYMBOL_PAD = \d+', f'SYMBOL_PAD = {a.n}', src, flags=re.M)
    assert k == 1, 'SYMBOL_PAD line not found'
    with open(CPP, 'rb') as f:
        cpp = f.read().decode('latin-1')
    padded = with_pad(cpp, a.n)
    if new != src:
        with open(AUXROOTS, 'wb') as f:
            f.write(new.encode('utf-8'))
    if padded != cpp:
        with open(CPP, 'wb') as f:
            f.write(padded.encode('latin-1'))
    print(f'auxpad: SYMBOL_PAD = {a.n} (tools/re/auxroots.py, app/client/co.cpp)')
    return 0


def parser():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    s = sub.add_parser('sweep')
    s.add_argument('--from', dest='lo', type=int, default=0)
    s.add_argument('--to', dest='hi', type=int, default=63)
    s.add_argument('--agent', metavar='NAME', help='importer agent: lock owner, scratch under .work/NAME/tmp')
    s.add_argument('--hold', action='store_true', help='take the importer lock once and hold it for the whole sweep')
    s.add_argument('--lockfree', action='store_true',
                   help="no importer lock (a git worktree with its leased VM only; sendpad.py's lock_free): the same "
                        'compile and match, ~3 s a value')
    vm = s.add_mutually_exclusive_group()
    vm.add_argument('--host', metavar='IP', help='use this build VM instead of leasing one')
    vm.add_argument('--pool', nargs='?', const=1, type=int, choices=[1], metavar='1',
                    help='lease one VM from pool.py (the default)')
    s.add_argument('--holder-pid', type=int, help="the lease's holder pid (pool.py's default otherwise)")
    s.add_argument('--sets', default=os.path.join(REPO, '.work', 'log', 'auxpad-sets.json'), metavar='PATH',
                   help="every value's exact address set, as JSON (default %(default)s)")
    t = sub.add_parser('set')
    t.add_argument('n', type=int)
    return ap


def held_sweep(a):
    """sweep(a); with --hold the lock the first value takes is given back here, on every exit."""
    global HOLD
    HOLD = bool(getattr(a, 'hold', False))
    try:
        return sweep(a)
    finally:
        if HOLD:
            HOLD = False
            import importer
            importer.release_lock()


def main(argv=None):
    a = parser().parse_args(argv)
    raise SystemExit(held_sweep(a) if a.cmd == 'sweep' else set_pad(a))


if __name__ == '__main__':
    main()
