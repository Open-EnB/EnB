"""Sweep and set SYMBOL_PAD, the symbol pad at the end of app/client/aux_roots.cpp (workflow.md 3.3).

Every declaration aux_roots.cpp sees moves its six end-of-file template constructors along a cycle of
64 VC6 tie-breaks; each is exact only in a window. tools/re/auxroots.py's SYMBOL_PAD (an enum of N
enumerators) puts the file inside the windows; retune it when a header aux_roots.cpp includes gains or
loses declarations.

  auxpad.py sweep [--from 0 --to 63] [--agent NAME] [--host IP | --pool]
      compile aux_roots.cpp alone with each pad value (~5 s a variant), print pad -> which of the six
      constructors are exact, and the windows where all six are
  auxpad.py set N [--client EXE]
      write SYMBOL_PAD = N in tools/re/auxroots.py and regenerate aux_roots.h/.cpp as auxroots.py does

sweep takes the importer lock per variant (the tree's aux_roots.cpp holds the variant only inside it and
is restored after), never for the whole sweep. VMs: --host IP uses that build VM; otherwise one VM is
leased from pool.py and released at the end (also on failure). Measuring logic: HX1's exp.py.
"""
import argparse
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
AUXROOTS = os.path.join(REPO, 'tools', 're', 'auxroots.py')
CPP = os.path.join(REPO, 'app', 'client', 'aux_roots.cpp')
WATCH = ['0x6FB1E0', '0x702240', '0x7045F0', '0x7014B0', '0x701D70', '0x758210']
ENUM = re.compile(r'\r?\n// VC6 symbol pad \(not the client\'s code\).*?\r?\nenum AuxRootsSymbolPadType \{[^}]*\};[^\r\n]*\r?\n',
                  re.S)


def with_pad(text, n):
    """text (aux_roots.cpp, CRLF) with the pad block holding n enumerators (0: no block)."""
    m = ENUM.search(text)
    assert m, 'aux_roots.cpp has no symbol pad block (generated by tools/re/auxroots.py)'
    if n == 0:
        return text[:m.start()] + '\n' + text[m.end():]
    block = m.group(0)
    enums = ', '.join(f'AUX_ROOTS_PAD_{i:02d}' for i in range(n))
    block = re.sub(r'(enum AuxRootsSymbolPadType \{)[^}]*(\};)', lambda k: f'{k.group(1)} {enums} {k.group(2)}', block)
    return text[:m.start()] + block + text[m.end():]


def measure(importer, n, orig):
    """Compile aux_roots.cpp with pad n under the importer lock (taken and given back here)."""
    importer.hold_lock()
    try:
        with open(CPP, 'wb') as f:
            f.write(with_pad(orig.decode('latin-1'), n).encode('latin-1'))
        found, text = importer.compile_and_match([CPP], f'auxpad-{n}')
        got = set().union(*found.values()) if found else set()
        errs = [l for l in text.splitlines() if ' error ' in l][:3]
        return got, errs
    finally:
        with open(CPP, 'wb') as f:
            f.write(orig)
        importer._release_lock()
        importer._lock_held = False


def windows(ok):
    runs, start, prev = [], None, None
    for n in ok + [None]:
        if start is not None and (n is None or n != prev + 1):
            runs.append((start, prev))
            start = None
        if n is not None and start is None:
            start = n
        prev = n
    return runs


def sweep(a):
    import contextlib
    import importer
    if a.agent:
        importer.set_agent(a.agent)
    if a.host:
        os.environ['ENB_VC6_HOSTS'] = a.host if '@' in a.host else 'Daniel@' + a.host
        lease = contextlib.nullcontext()
    else:
        lease = importer.pool_lease(1, a.holder_pid)
    rows, ok = [], []
    with lease:
        for n in range(a.lo, a.hi + 1):
            orig = open(CPP, 'rb').read()          # re-read: the tree may change between variants
            got, errs = measure(importer, n, orig)
            exact = [w for w in WATCH if w in got]
            line = f'{n:3d}  {len(exact)}/6  ' + ' '.join(w + ('+' if w in got else '-') for w in WATCH) + \
                   f'  total {len(got)}' + (f'  ERRORS {errs}' if errs else '')
            print(line, flush=True)
            rows.append(line)
            if len(exact) == len(WATCH):
                ok.append(n)
    print('\nall six exact:', ', '.join(f'{x}..{y}' if x != y else str(x) for x, y in windows(ok)) or 'none')
    return 0 if ok else 1


def set_pad(a):
    with open(AUXROOTS, 'rb') as f:
        src = f.read().decode('utf-8')
    new, k = re.subn(r'^SYMBOL_PAD = \d+', f'SYMBOL_PAD = {a.n}', src, flags=re.M)
    assert k == 1, 'SYMBOL_PAD line not found'
    with open(AUXROOTS, 'wb') as f:
        f.write(new.encode('utf-8'))
    cmd = [sys.executable, AUXROOTS, 'generate']
    if a.client:
        cmd += ['--client', a.client]
    return subprocess.call(cmd)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest='cmd', required=True)
    s = sub.add_parser('sweep')
    s.add_argument('--from', dest='lo', type=int, default=0)
    s.add_argument('--to', dest='hi', type=int, default=63)
    s.add_argument('--agent', metavar='NAME', help='importer agent: lock owner, scratch under .work/NAME/tmp')
    s.add_argument('--host', metavar='IP', help='use this build VM instead of leasing one')
    s.add_argument('--holder-pid', type=int, help="the lease's holder pid (pool.py's default otherwise)")
    t = sub.add_parser('set')
    t.add_argument('n', type=int)
    t.add_argument('--client')
    a = ap.parse_args()
    raise SystemExit(sweep(a) if a.cmd == 'sweep' else set_pad(a))


if __name__ == '__main__':
    main()
