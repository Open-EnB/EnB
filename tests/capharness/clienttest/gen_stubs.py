"""clienttest's generated sources (tools/harness/clienttest.py build runs it into the stage).

    python tests/capharness/clienttest/gen_stubs.py OUTDIR
    python tests/capharness/clienttest/gen_stubs.py --link LINK.LOG OUTDIR    (link_stubs.cpp, below)

Writes, from the tree (nothing under tools/re is changed: pkclasses.py stays P6's):
  pk_stubs.cpp        udpreplay's pk_ctor_stubs.cpp (pkclasses.py's output) without the
                      Process_Packet lines of the classes app/client/cpacket.cpp defines: cpacket.obj
                      supplies those (P-T8-1). The constructors hand the raw message to Conn_Record
                      (clienttest.cpp), as in udpreplay.
  clienttest_tables.cpp
                      per opcode of the factory's switch (app/packets/pk.cpp): the name
                      (docs/data/packet-factory.txt), the class, and whether clienttest drives its
                      handler (cpacket.cpp defines the class's Process_Packet and the class's raw
                      constructor is rebuilt, i.e. not a pk_ctor_stubs.cpp line). The others go to the
                      harness's recording packet.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
PK_CTOR_STUBS = os.path.join(REPO, 'tests', 'capharness', 'udpreplay', 'pk_ctor_stubs.cpp')
CPACKET = os.path.join(REPO, 'app', 'client', 'cpacket.cpp')
PK_CPP = os.path.join(REPO, 'app', 'packets', 'pk.cpp')
FACTORY = os.path.join(REPO, 'docs', 'data', 'packet-factory.txt')
# cpacket.cpp's handlers clienttest records instead of driving: CREATE 4's models come from co.cpp's loader
# 0x6F5140, which needs the game's asset manager (*0xBDADC0, a stand-in here), so clienttest.cpp makes its own objects;
# CHANGE_BASE_ASSET 38 loads a model the same way, and SUBPARTS 180 ends in co.cpp's 0x6FCB70, which loads six bone models
# with it (and calls slot +0xF8 of the model, which the harness's fake models don't have)
NOT_DRIVEN = {'CreatePacketClass', 'ChangeBaseAssetPacketClass', 'SubPartsPacket'}


def read(p):
    return open(p, encoding='latin1').read()


def cpacket_classes():
    """The classes whose Process_Packet cpacket.cpp defines."""
    return set(re.findall(r'^bool (\w+)::Process_Packet\(void \*\w*\)\s*$', read(CPACKET), re.M))


def main(out):
    handled = cpacket_classes()
    stub_lines = read(PK_CTOR_STUBS).splitlines()
    stubbed_ctor = set()
    kept, dropped = [], []
    for line in stub_lines:
        m = re.match(r'^(\w+)::\1\(RawPacketClass \*raw\)', line)
        if m:
            stubbed_ctor.add(m.group(1))
        m = re.match(r'^bool (\w+)::Process_Packet\(', line)
        if m and m.group(1) in handled:
            dropped.append(m.group(1))
            continue
        if line.startswith('// GENERATED by tools/re/pkclasses.py') or line.startswith('// (udpreplay --conn)'):
            continue
        kept.append(line)
    text = ("// GENERATED by tests/capharness/clienttest/gen_stubs.py from udpreplay's pk_ctor_stubs.cpp (tools/re/\n"
            "// pkclasses.py), without the %d Process_Packet lines cpacket.cpp defines: the packet classes' raw\n"
            "// constructors hand the message to Conn_Record (clienttest.cpp).\n" % len(dropped)) + '\n'.join(kept)
    with open(os.path.join(out, 'pk_stubs.cpp'), 'w', newline='\r\n') as f:
        f.write(text + '\n')

    names = {}
    for line in read(FACTORY).splitlines():
        m = re.match(r'^\s*(\d+)\s+0x[0-9A-F]+\s+(\S+)', line)
        if m:
            names[int(m.group(1))] = m.group(2)
    cases = [(int(o), c) for o, c in re.findall(r'case (\d+):\s*\n\s*packet = new (\w+)\(raw\);', read(PK_CPP))]
    rows, driven, waiting = [], 0, []
    for op, cls in sorted(cases):
        if cls in handled and cls not in stubbed_ctor and cls not in NOT_DRIVEN:
            mode = 1
            driven += 1
        elif cls in handled:
            mode = 2
            waiting.append(cls)
        else:
            mode = 0
        rows.append('\t{ %d, "%s", "%s", %d },' % (op, names.get(op, '?'), cls, mode))
    with open(os.path.join(out, 'clienttest_tables.cpp'), 'w', newline='\r\n') as f:
        f.write('// GENERATED by tests/capharness/clienttest/gen_stubs.py: the factory\'s opcodes (pk.cpp), their\n'
                '// names (docs/data/packet-factory.txt) and classes; Handler 1: cpacket.cpp\'s handler with a rebuilt\n'
                '// raw constructor (driven), 2: cpacket.cpp\'s handler but the constructor is a stub (recorded), 0: none.\n'
                '#include "clienttest.h"\n\n'
                'const OpcodeInfo Opcode_Table[] = {\n' + '\n'.join(rows) + '\n};\n'
                'const int Opcode_Count = %d;\n' % len(rows))
    print('gen_stubs: %d Process_Packet stub lines dropped (cpacket.cpp), %d opcodes, %d driven, %d with a stub '
          'constructor%s' % (len(dropped), len(rows), driven, len(waiting), (': ' + ', '.join(waiting)) if waiting else ''))


# ------------------------------------------------------------------------- link_stubs.cpp: the rest

UNRES = re.compile(r'unresolved external symbol "(.*?)" \((\S+)\)')
SCALARS = ('bool', 'char', 'unsigned char', 'short', 'unsigned short', 'int', 'unsigned int', 'long',
           'unsigned long', 'float', 'double', '__int64', 'unsigned __int64', 'signed char')
STD = [('class std::basic_string<char,struct std::char_traits<char>,class std::allocator<char> >', 'std::string')]
FUNC = re.compile(r'^(?:(public|protected|private): )?(?:(static|virtual) )?(.*?)\s*(__thiscall|__cdecl|__stdcall|__fastcall) '
                  r'([\w:~]+)\((.*)\)(const)?$')
DATA = re.compile(r'^(?:(public|protected|private): )?(?:(static) )?(.*?)\s*([\w:]+)$')


def tidy(t):
    for a, b in STD:
        t = t.replace(a, b)
    return t.strip()


def returnable(ret):
    """The stub's return statement for RET, or None when the type can't be made here (a class by value)."""
    if ret in ('', 'void'):
        return ''
    if ret.endswith('*') or ret in SCALARS or ret.startswith('enum '):
        return ' return(0);'
    if ret.endswith('&'):
        return ' static char zero[256]; return(*(%s)zero);' % (ret[:-1].strip() + ' *')
    return None


def link_stubs(log, out):
    """A logging stand-in for each symbol LOG (a VC6 link.log) lists as unresolved: free functions,
    members (each class declared here with only those members, so no vtable is emitted unless a
    constructor or destructor of a class with virtuals is among them) and data (zero). What can't be
    written from the demangled name (a class by value, an enum, a nested or template class) is listed
    as skipped for client_stubs.cpp."""
    syms = {}
    for m in UNRES.finditer(open(log, encoding='latin1').read()):
        syms[m.group(2)] = m.group(1)
    fwd, classes, defs, skipped = set(), {}, [], []

    def types(text):
        for kind, name in re.findall(r'\b(class|struct|union) ([A-Za-z_]\w*(?:::\w+)*)', text):
            if name.startswith('std::'):
                continue
            if '::' in name:
                return False
            fwd.add((kind, name))
        return 'enum ' not in text

    for mangled, dem in sorted(syms.items(), key=lambda kv: kv[1]):
        dem = tidy(dem)
        m = FUNC.match(dem)
        if m:
            access, storage, ret, conv, qual, args, const = m.groups()
            ret, args = tidy(ret), tidy(args)
            body = returnable(ret)
            # a class or struct by value (SClient::Do_Frame's KernelEventClass): needs its definition
            by_value = re.search(r'\b(?:class|struct|union) [\w:]+\s*(?:,|$)', args)
            if body is None or not types(ret + ' ' + args) or '<' in qual or by_value:
                skipped.append(dem)
                continue
            cls, _, name = qual.rpartition('::')
            const = ' const' if const else ''
            text = '%s(%s)%s' % (name, args, const)
            if cls:
                if '::' in cls:
                    skipped.append(dem)
                    continue
                kind = 'struct' if ('struct ' + cls) in dem else 'class'
                decl = '%s%s%s;' % ((storage + ' ') if storage else '', (ret + ' ') if ret else '', text)
                classes.setdefault((kind, cls), {}).setdefault(access or 'public', []).append(decl)
                defs.append('%s%s::%s%s {%s Trace("gen %s");%s }' % ((ret + ' ') if ret else '', cls, name,
                            '(%s)%s' % (args, const), '', qual, body))
            else:
                conv_text = '' if conv == '__cdecl' else conv + ' '
                defs.append('%s %s%s(%s) { Trace("gen %s");%s }' % (ret, conv_text, name, args, qual, body))
            continue
        m = DATA.match(dem)
        if m:
            access, storage, typ, qual = m.groups()
            typ = tidy(typ)
            if not (typ.endswith('*') or typ in SCALARS) or not types(typ) or '<' in qual:
                skipped.append(dem)
                continue
            cls, _, name = qual.rpartition('::')
            if cls:
                classes.setdefault(('class', cls), {}).setdefault(access or 'public', []).append('static %s %s;' % (typ, name))
                defs.append('%s %s::%s = 0;' % (typ, cls, name))
            else:
                defs.append('%s %s = 0;' % (typ, name))
            continue
        skipped.append(dem)
    lines = ['// GENERATED by tests/capharness/clienttest/gen_stubs.py --link from the previous link\'s unresolved',
             '// symbols: a logging stand-in for each (the trace shows "gen NAME" if a test reaches one).',
             '#include <string>', '#include <vector>', '#include "clienttest.h"', '']
    defined = set(classes)
    for kind, name in sorted(fwd):
        if (kind, name) not in defined and ('class', name) not in defined and ('struct', name) not in defined:
            lines.append('%s %s;' % (kind, name))
    for (kind, name), members in sorted(classes.items()):
        lines.append('%s %s' % (kind, name))
        lines.append('{')
        for access in ('public', 'protected', 'private'):
            if access in members:
                lines.append('%s:' % access)
                lines += ['\t' + d for d in members[access]]
        lines.append('};')
    lines.append('')
    lines += defs
    for s in skipped:
        lines.append('// skipped (write it in client_stubs.cpp): ' + s)
    with open(os.path.join(out, 'link_stubs.cpp'), 'w', newline='\r\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('gen_stubs --link: %d unresolved, %d stand-ins written, %d skipped%s' % (
        len(syms), len(syms) - len(skipped), len(skipped), ''.join('\n  skipped: ' + s for s in skipped)))
    return len(skipped)


if __name__ == '__main__':
    if len(sys.argv) == 4 and sys.argv[1] == '--link':
        link_stubs(sys.argv[2], sys.argv[3])
    elif len(sys.argv) == 2:
        main(sys.argv[1])
    else:
        raise SystemExit(__doc__)
